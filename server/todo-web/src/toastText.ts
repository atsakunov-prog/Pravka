// Тексты тостов — как у Todoist (его собственный русский перевод, 19.10): одно место на весь веб. Склонения — plural4.

import { addDays, plural4, shortDate } from './dates.ts';

/** День в тосте: «сегодня», «завтра», иначе «26 окт». */
export function dayWords(d: string, today: string): string {
  if (d === today) return 'сегодня';
  if (d === addDays(today, 1)) return 'завтра';
  return shortDate(d, today);
}

/** «в» или «во»: «во Входящие», «в Альфа Групп». */
const into = (where: string) => (/^[вф][^аеёиоуыэюя]/i.test(where) ? 'во ' : 'в ') + where;

export const T = {
  done: (n = 1) => (n === 1 ? 'Задача выполнена' : plural4(n, ['{n} задача выполнена', '{n} задачи выполнено', '{n} задач выполнено', '{n} задачи выполнено'])),
  /** Вторая строка тоста выполненного повтора. */
  next: (d: string, today: string) => 'Следующий раз: ' + dayWords(d, today),
  /** Повтор сбросил выполненные дела внутри: все — «Выполнена и снова добавлена 1 подзадача», часть — «… 2 из 5 подзадач». */
  reset: (n: number, total = n) => (n < total ? `Выполнено и снова добавлено ${n} из ${total} подзадач`
    : plural4(n, ['Выполнена и снова добавлена {n} подзадача', 'Выполнено и снова добавлено {n} подзадачи', 'Выполнено и снова добавлено {n} подзадач',
      'Выполнено и снова добавлено {n} подзадачи'])),
  /** «Отложить», «Перенести» у просроченных: дата одна — с ней, у каждого своя — без. */
  rescheduled: (d: string | null, today: string) => (d ? 'Перенесено на ' + dayWords(d, today) : 'Перенесено'),
  due: (d: string | null, today: string) => (d ? 'Срок изменен на ' + dayWords(d, today) : 'Срок снят'),
  deadline: (d: string | null, today: string) => (d ? 'Дедлайн изменен на ' + dayWords(d, today) : 'Дедлайн снят'),
  moved: (where: string, n = 1) => (n === 1 ? 'Задача перенесена ' : 'Задачи перенесены ') + into(where),
  reordered: 'Порядок изменен',
  sectionMoved: (where: string) => 'Раздел перенесен ' + into(where),
  added: (where: string, n = 1) => (n === 1 ? 'Задача добавлена ' + into(where) : plural4(n, ['{n} задача добавлена', '{n} задачи добавлено', '{n} задач добавлено', '{n} задачи добавлено'])),
  deleted: (n = 1) => (n === 1 ? 'Задача удалена' : plural4(n, ['{n} задача удалена', '{n} задачи удалено', '{n} задач удалено', '{n} задачи удалено'])),
  priority: (p: number) => (p < 4 ? 'Приоритет ' + p : 'Без приоритета'),
  viewReset: 'Восстановлены параметры отображения по умолчанию',
};
