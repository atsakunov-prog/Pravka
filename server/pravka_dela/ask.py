def _task_context(url: str, user: str, text: str, scope: dict) -> dict:
    """Карточка дела (scope.card = "task"): Claude видит только это дело — без экрана и без остальных дел. Справочник
    и правила — тот же system, что у строки страницы (кэш общий у одной модели)."""
    tid = str(scope.get("open") or scope.get("focus") or "")
    talk = _history(scope)
    with db.session(url, user, via="ask") as conn:
        t = conn.execute("SELECT * FROM tasks.v_tasks WHERE id = %s", (tid,)).fetchone() if tid else None
        if not t:
            raise AskError("этого дела нет или оно не видно — открой его заново")
        cat, index = _catalog(conn)
        today = conn.execute("SELECT crm.today() AS d").fetchone()["d"]
        me = conn.execute("SELECT name, id = crm.owner_id() AS owner FROM crm.users WHERE id = %s", (user,)).fetchone()
        now_ids = {str(r["id"]) for r in conn.execute(
            "SELECT id FROM tasks.tasks WHERE owner_id = %s AND status = 'open' AND focus_on = crm.today()", (user,)).fetchall()}
        index["places"] = places = remind.places_of(conn, user)
        hm = conn.execute("SELECT to_char(now() AT TIME ZONE 'Europe/Moscow', 'HH24:MI') AS hm").fetchone()["hm"]
        lines, card, near = _task_card(conn, url, user, t, today)
        # Остальные свои открытые — одной строкой (15.10.2026): «положи это в дело про термшит», «вложи сюда драфт» —
        # Claude должен найти, куда (или что) вложить (into). Только когда о вложении речь (NEST_WORDS — в команде или
        # разговоре) и не в «Для этого» (там правки дела всё равно отбрасываются): до 400 строк — 8–10 тыс. токенов
        # Opus к каждому холодному вызову карточки (~$0,05), а нужны они редко. И хвостом, а не в голове экрана: голова
        # карточки кэшируется на разговор, и список в ней остался бы с первой реплики.
        talk_said = " ".join(str(x.get("said") or "") for x in scope.get("history") or [] if isinstance(x, dict))
        want_others = not scope.get("step") and bool(NEST_WORDS.search(text + " " + talk_said))
        others = conn.execute(
            "SELECT * FROM tasks.v_tasks WHERE owner_id = %s AND status = 'open' AND id <> %s AND NOT goal "
            "ORDER BY project_name NULLS FIRST, due_date NULLS LAST, num LIMIT %s",
            (user, t["id"], MAX_OTHER)).fetchall() if want_others else []
    model, effort = llm.route(url, TASK_ROUTE)
    msg = ["Календарь: " + _calendar(today), "Страница: карточка дела"]
    if me and not me["owner"]:
        msg.append(f"Команду даёт не Саша, а {me['name']}: «Саша» и mine выше — про этого человека.")
    msg += ["", *lines]
    screen = _snapshot(user, scope.get("talk_id"), "\n".join(msg))
    tail = [f"Сегодня {today.isoformat()}, {WD[today.weekday()]}, сейчас {hm}.", f"В «Сейчас» сегодня: {len(now_ids)} из {NOW_MAX}."]
    if others:
        tail += ["", f"ДРУГИЕ МОИ ОТКРЫТЫЕ ДЕЛА ({len(others)}) — только чтобы вложить это дело в одно из них или одно из "
                     "них сюда (into), больше их не правь:"]
        group = object()
        for r in others:
            if r["project_name"] != group:
                group = r["project_name"]
                tail.append(f"{group or 'Входящие'}:")
            tail.append(_task_line(r, today, short=True))
    if talk:
        tail += ["", "РАЗГОВОР — команда ниже его продолжение (старое сверху; сделанное уже применено):", *talk]
    head = ("ДЛЯ ЭТОГО — Саша называет, что сделать для этого дела: " if scope.get("step")
            else "КСТАТИ — Саша вдогонку к этому делу: " if scope.get("kstati") else "КОМАНДА: ")
    tail += ["", head + text]
    system = (SYSTEM.replace("{REMIND}", remind_rules(url)).replace("{CATALOG}", cat)
              .replace("{PLACES}", remind.places_block(places)))
    # Шаг к этому делу (15.10.2026): что он берёт от дела — одно правило store.step_of (веб и телефон — так же).
    step = {"parent": t, "near": store.step_of(t, user, today), "only": bool(scope.get("step"))}
    return {"text": text, "system": system, "message": screen + "\n\n" + "\n".join(tail), "screen": screen,
            "tail": "\n".join(tail), "model": model, "effort": effort,
            "tasks": {t["num"]: t}, "focused": t, "sugs": {}, "targets": {}, "index": index, "today": today,
            "card": card, "now_ids": now_ids, "near": near, "step": step, "pool": {**{r["num"]: r for r in others}, t["num"]: t}}


def _when_words(due, today: dt.date) -> str:
    """Срок шага словами для reply: «на сегодня», «на завтра», «на 17.10», «без срока»."""
    d = store._day(due)
    if not d:
        return "без срока"
    return "на сегодня" if d == today else "на завтра" if d == today + dt.timedelta(days=1) else "на " + d.strftime("%d.%m")


def group_said(t: dict) -> str:
    """Повестка словами для reply (мелочи 16.10.2026, запись 19): «в повестку с Иваном Тестовым». В 12:23 Саша завёл
    «Обсудить с … грантовое финансирование» — оно легло в повестку, а ответ сказал только «без срока», и повестки он не
    увидел. Не повестка — пусто."""
    if t.get("ball") != "agenda":
        return ""
    from . import capture

    name = t.get("person_name") or t.get("person_short")
    return f"в повестку с {capture.instrumental(name)}" if name else "в повестку"


def _step_bit(x: dict, today: dt.date) -> str:
    when, grp = _when_words(x.get("due_date"), today), group_said(x)
    if grp:
        when = grp if when == "без срока" else f"{when}, {grp}"
    return f"«{x['title']}», {when}" + (", в «Сейчас»" if store._day(x.get("focus_on")) == today else "")


def agenda_said(created: list[dict], made: list[dict]) -> str:
    """Дела в повестку, заведённые не внутри дела (строка карточки, «завести» Claude): «Обсудить …» — в повестку с … —
    строкой сервера: Claude группу в reply может не назвать (запись 19)."""
    inside = {str(x["id"]) for x in made}
    return " ".join(f"«{x['title']}» — {g}." for x in created if str(x["id"]) not in inside and (g := group_said(x)))


def steps_said(parent: dict, made: list[dict], today: dt.date) -> str:
    """Строка reply о делах, заведённых внутри этого (сервер пишет её сам, Claude их в reply не называет): «Завёл для
    «…»: «…», на сегодня». «Шаг» — не имя сущности (владелец 15.10.2026: это обычные дела внутри дела). Не вложилось
    (дело чужое — «Зачем» ставит только хозяин) — честно: заведено отдельным делом. Повестка — «в повестку с …»
    вместо «без срока» (запись 19)."""
    if not made:
        return ""
    bits = "; ".join(_step_bit(x, today) for x in made)
    if all(str(x.get("why_id") or "") == str(parent["id"]) for x in made):
        return f"Завёл для «{parent['title']}»: {bits}."
    return f"Завёл {bits} — отдельно: вложить в «{parent['title']}» может только его хозяин."


def raised_said(raised: list[dict]) -> str:
    """Сделано последнее дело внутри — родитель поднялся (store._nest_rise): «Всё внутри сделано — теперь: «…»»."""
    return " ".join(f"Всё внутри сделано — теперь: «{r['title']}»" + (", на сегодня" if r.get("moved") else "") + "."
                    for r in raised)


def fell_said(fell: list[dict], today: dt.date) -> str:
    """Дело внутри снова открыто — подъём родителя отменён (tasks.nest_fall): «Срок «…» — снова на 20.10.»"""
    return " ".join(f"Срок «{r['title']}» — снова {_when_words(r.get('due_date'), today)}." for r in fell)


# Захват (15.10.2026, capture.py): строка веба — та же дверь, что «сказать» и «Д». Фраза, которую правило узнаёт
# («напомни в 12 …», «позвонить Ивану на неделе», «идея: …», «Иван сказал …», «позвонил Ольге»), раскладывается без
# Claude — и без ключа; route «new» от Claude — та же раскладка корзинами, что у телефона (capture.say_now).
# rule_tried — правило уже молчало в api.ask_start (до суточного предела): второй раз его не спрашиваем.
RULE_SKIP = ("history", "card", "project_id", "person_id", "deal_id", "selected_ids", "open", "focus", "step", "kstati",
             "rule_tried")
# Строка веба — ещё и правка того, что на экране: «перенести на завтра», «закрыть все просроченные», «это в сейчас».
# Такие команды правилу захвата не отдаём — иначе «перенести» стало бы новым делом. У «Д» на телефоне этой развилки нет:
# туда говорят только новое. Вложенность (правило 27, поезд 16.10.2026): «вложи / положи / вынь …» — тоже правка (Claude:
# changes.into); остальные слова вложенности («для этого», «внутри», «к делу про …») правило захвата не берёт само
# (capture.NEST_SAID).
EDIT_FIRST = frozenset("""перенести перенеси закрыть закрой отменить отмени удалить удали убрать убери поменять поменяй
переименовать переименуй сдвинуть сдвинь отложить отложи принять прими отклонить отклони назначить назначь отдать отдай
поставить поставь снять сними вернуть верни объединить объедини вложить вложи положи переложить переложи вынуть вынь
засунуть засунь""".split())
SCREEN_WORDS = re.compile(r"(?:^|\s)(?:это|эти|этих|этому|его|их|все|всё|просроченн\w*|выбранн\w*|#\d+|п\d+)(?:$|[\s,.!?:])", re.I)


def rule_first(url: str, user: str, text: str, scope: dict, via: str = "web", actor: str | None = None) -> dict | None:
    """Правило захвата до Claude: в разговоре, в карточке, на странице проекта, человека или сделки и при выбранных
    делах — нет (там «это» и экран важнее); команда про экран («перенести…», «эти…», «все просроченные») — тоже нет.
    Узнало — ответ строки (route «capture»), нет — None."""
    if any(scope.get(k) for k in RULE_SKIP):
        return None
    words = text.lower().replace("ё", "е").split()
    if not words or words[0].strip(",.:!") in EDIT_FIRST or SCREEN_WORDS.search(text.lower().replace("ё", "е")):
        return None
    got = store.apply_ops(url, user, [{"op": "capture.say", "text": text, "ref": str(uuid.uuid4()), "lane": "rule",
                                       "from": "web"}], via, actor)["results"][0]
    if not got.get("ok") or (got.get("capture") or {}).get("status") in (None, "none"):
        return None
    from . import capture

    cap = got["capture"]
    tasks, notes = capture.rows_of(url, user, cap)
    return {"route": "capture", "reply": "", "changed": [], "decided": [], "crm": [], "tasks": tasks, "notes": notes,
            "errors": [x["error"] for x in cap.get("items") or [] if x.get("bucket") == "error"], "refs": [],
            "usage": None, "capture": cap}


def run(url: str, user: str, text: str, scope: dict, key: str, proxy: str | None,
        via: str = "web", actor: str | None = None, ask_fn=None, parse_fn=None) -> dict:
    """Команда → правки (или разбор новых дел) → применить. ask_fn/parse_fn — подмена Claude в тестах.
    Что видит Claude — context (там же scope). Сначала — правило захвата (rule_first): узнало — Claude не нужен."""
    first = rule_first(url, user, text, scope, via, actor)
    if first:
        return first
    ctx = context(url, user, text, scope)
    text, model, effort = ctx["text"], ctx["model"], ctx["effort"]
    tasks, focused, sugs, targets = ctx["tasks"], ctx["focused"], ctx["sugs"], ctx["targets"]
    index, today, card, now_ids = ctx["index"], ctx["today"], ctx["card"], ctx["now_ids"]
    step = ctx.get("step")  # карточка дела: шаг к ней (15.10.2026)
    only = bool(step and step["only"])
    plain_title = " ".join(text.split())[:500]
    plain = False
    plain_note = ""  # почему «Для этого» обошлось без Claude (кроме «нет ключа» — там Claude и не ждут)
    by_title = lambda s, u: {"route": "edit", "reply": "", "changes": [], "create": [{"title": plain_title, "step": True}]}  # noqa: E731
    if ask_fn is None:
        if only and (not key or scope.get("no_claude")):
            # «Для этого» без Claude — шаг названием, как сказано, тем же правилом связи и срока (store.step_of): без
            # ключа или сверх суточного предела не-владельцу (api.ask_start ставит no_claude вместо ответа 429).
            plain = True
            ask_fn = by_title
            if key:
                plain_note = "Claude на сегодня для тебя — всё: завёл названием, как сказано."
        elif not key:
            raise AskError("Claude не настроен: нет ключа в dela.env")
        else:
            # Защита от петли (аудит №12, guard.py): задача — ask или task (карточка дела); стоит — ошибка словами.
            cl = guard.client(url, key, proxy, "task" if scope.get("card") == "task" else "ask")
            ask_fn = lambda s, u: ask(cl, s, ctx["tail"], model, effort, prefix=ctx["screen"])  # noqa: E731
    try:
        data = ask_fn(ctx["system"], ctx["message"])
    except guard.Stopped:
        if not only:
            raise
        # «Для этого» при стоящей защите от петли — так же названием (правило 27: «работает и без Claude»; стык вагонов
        # поезда 16.10). Защита останавливает ДО вызова: платного ответа не было, в книгу трат писать нечего.
        plain, data = True, by_title(None, None)
        plain_note = "Claude стоит защитой от петли: завёл названием, как сказано."
    except AskError as e:  # ответ оплачен, но не годится — траты всё равно в книгу
        llm.account_failed(url, "task" if scope.get("card") == "task" else "ask", e, model)
        raise
    if only:
        # «Для этого»: само дело не меняется — только шаги; Claude ничего не завёл — шаг названием, как сказано (поле
        # «Для этого» без шага — ровно жалоба владельца 15.10.2026: «добавляет в комментарии вместо нового дела»).
        data["changes"], data["card"], data["suggestions"] = [], [], []
        if not any((x.get("title") or "").strip() for x in data.get("create") or []):
            data["create"] = [{"title": plain_title, "step": True}]
    if data.get("card"):
        for k, v in split_card(data["card"]).items():
            data[k] = (data.get(k) or []) + v
    usage = data.get("_usage")
    in_task = scope.get("card") == "task"
    if not plain:
        llm.account(url, "task" if in_task else "ask", llm.cost(usage, model, url), (usage or {}).get("model") or model,
                    usage=usage)
    defaults = {k: scope[k] for k in ("project_id", "person_id", "deal_id") if scope.get(k)}
    if card and card["kind"] == "deal":
        defaults["project_id"] = str(card["deal"]["project_id"])
    if in_task:  # новое из карточки дела — рядом с ним: тот же проект, сделка и цель
        defaults = dict(ctx.get("near") or {})
    if (data.get("route") == "new" and not focused and not in_task and not data.get("suggestions") and not scope.get("history")
            and not any(data.get(k) for k in ("notes", "people", "deals", "about", "clients"))):
        # Команда целиком про новые дела — та же раскладка, что у «Д» и «сказать» (захват, 15.10.2026): разбор
        # надиктовки (тот же промпт, что у телефона, с блоком КОРЗИНЫ), корзины — кодом, строки и кнопки — в capture.
        from . import capture

        try:
            cap = capture.say_now(url, user, text, "web", key, proxy, via=via, actor=actor, ask_fn=parse_fn,
                                  skip_rule=True, defaults={k: v for k, v in defaults.items() if k != "deal_id"})
        except capture.CaptureError as e:
            raise AskError(str(e)) from None
        tasks_, notes_ = capture.rows_of(url, user, cap)
        out = {"tasks": tasks_, "notes": notes_, "capture": cap,
               "errors": [x["error"] for x in cap.get("items") or [] if x.get("bucket") == "error"]}
        if defaults.get("deal_id"):  # на странице сделки новые дела — её шаги
            fix = [{"op": "task.set", "id": str(t["id"]), "set": {"deal_id": defaults["deal_id"]}} for t in out["tasks"]
                   if str(t.get("project_id")) == defaults["project_id"] and not t.get("deal_id")]
            if fix:
                got = store.apply_ops(url, user, fix, via, actor)["results"]
                byid = {str(r["task"]["id"]): r["task"] for r in got if r.get("ok") and r.get("task")}
                out["tasks"] = [byid.get(str(t["id"]), t) for t in out["tasks"]]
        return {"route": "new", "reply": "", "changed": [], "decided": [], "crm": [], **out, "usage": usage}
    sops, plan, smiss = sug_ops(data, sugs, targets, index, today)
    tops, undo, miss, step_at = to_ops(data, tasks, index, today, defaults, now_ids, step=step, pool=ctx.get("pool"))
    with db.session(url, user, via="ask") as conn:
        cops, cplan, cmiss = card_ops(conn, data, card, index, today)
    ops = sops + tops + cops
    res = store.apply_ops(url, user, ops, via, actor) if ops else {"results": []}
    results = res["results"]
    done, serr = decided(plan, results[:len(sops)])
    terr = [r["error"] for r in results[len(sops):len(sops) + len(tops)] if not r.get("ok")]
    crm_done, cerr = card_done(cplan, results[len(sops) + len(tops):])
    errors = serr + terr + cerr
    created = [r["task"] for o, r in zip(ops, results) if o["op"] == "task.create" and r.get("ok") and r.get("task")]
    if errors:
        log.warning("правка: не прошли %d из %d: %s", len(errors), len(ops), errors[0])
    refs = []
    for n in data.get("refs") or []:
        t = tasks.get(n)
        if t and str(t["id"]) not in {r["id"] for r in refs}:
            refs.append({"id": str(t["id"]), "num": t["num"], "title": t["title"]})
    # Шаги и поднятые дела — строкой сервера (15.10.2026): Claude шагов в reply не называет, срок считает сервер.
    made = [r["task"] for r in (results[len(sops) + i] for i in step_at) if r.get("ok") and r.get("task")]
    raised = [r["raised"] for r in results if r.get("ok") and r.get("raised")]
    fell = [r["fell"] for r in results if r.get("ok") and r.get("fell")]
    # «Для этого»: строка сервера и есть ответ — «Готово.» модели к ней ничего не добавляет (проба 15.10.2026).
    said = (data.get("reply") or "").strip() if not (only and made) else ""
    reply = " ".join(x for x in [steps_said(step["parent"], made, today) if step else "", agenda_said(created, made),
                                 raised_said(raised), fell_said(fell, today), said, plain_note] if x)
    return {"route": "edit", "reply": reply, "changed": undo, "tasks": created, "decided": done,
            "crm": crm_done, "notes": [], "errors": errors + smiss + miss + cmiss, "usage": usage, "refs": refs[:MAX_REFS],
            "model": (usage or {}).get("model") or model, "steps": [str(x["id"]) for x in made], "raised": raised,
            "fell": fell}
