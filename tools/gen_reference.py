def slug(name):
    """Стабильный id: он попадает в дневник, и переименование в Notion его не ломает."""
    table = {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
        "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
        "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
        "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
        "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    }
    out = []
    for ch in name.lower():
        if ch in table:
            out.append(table[ch])
        elif ch.isalnum():
            out.append(ch)
        else:
            out.append("-")
    s = re.sub(r"-+", "-", "".join(out)).strip("-")
    return s[:48]


def write(name, payload):
    os.makedirs(ASSETS, exist_ok=True)
    path = os.path.join(ASSETS, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=1, sort_keys=False)
        f.write("\n")
    size = os.path.getsize(path)
    print("%s: %d записей, %.1f КБ" % (name, len(payload.get("items", [])), size / 1024.0))


def build_exercises(rows):
    items = []
    for r in rows:
        name = r["Упражнение"]
        items.append({
            "id": slug(name),
            "n": int(r["№"]),
            "name": name,
            "scheme": r.get("Схема") or "",
            "blocks": json.loads(r.get("Блок") or "[]"),
            "gear": json.loads(r.get("Инвентарь") or "[]"),
            "targets": json.loads(r.get("Что тренирует") or "[]"),
            "how": r.get("Как делать") or "",
            "mistakes": r.get("Главные ошибки") or "",
            "progression": r.get("Прогрессия") or "",
            "video": r.get("Видео (запрос)") or "",
            "garmin": r.get("Garmin Connect") or "",
            "notion": r.get("url") or "",
            "unit": UNITS.get(name, "reps"),
            "aliases": ALIASES.get(name, []),
        })
    missing = [i["name"] for i in items if not i["aliases"]]
    if missing:
        print("ВНИМАНИЕ: без голосовых алиасов остались:", "; ".join(missing))
    return {"source": "notion:Упражнения", "snapshot": SNAPSHOT, "items": items}


def build_ration(rows):
    items = []
    for r in rows:
        name = r["Продукт"]
        items.append({
            "id": slug(name),
            "name": name,
            "meal": r.get("Приём") or "",
            "grams": r.get("Грамм") or 0,
            "kcal100": r.get("Ккал100") or 0,
            "p100": r.get("Б100") or 0,
            "f100": r.get("Ж100") or 0,
            "c100": r.get("У100") or 0,
            "note": r.get("Заметка") or "",
        })
    return {"source": "notion:Рацион", "snapshot": SNAPSHOT, "items": items}


