package ru.zf.pravka.core

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

// Чистка ответа модели: преамбулы, ёлочки и «мысли вслух» после ответа —
// три реальных случая из журнала 16.09.2026 (docs/agreements.md).
class ResponseCleanerTest {

    private val original = "Так окей переключайся на Уэспербейс не знаю мне кажется что это будет как-то быстрее по идее ну не знаю посмотрим давай"

    @Test
    fun `второй вариант после сомнения — остаётся он, рассуждение режется`() {
        val raw = "Так, окей, переключайся на Web3-базу. Не знаю, мне кажется, что это будет как-то быстрее по идее. Ну, не знаю, посмотрим, давай.\n\n" +
            "Хотя, если сомневаться в расшифровке названия — оставлю ближе к исходному звучанию:\n\n" +
            "Так, окей, переключайся на Уэспербейс. Не знаю, мне кажется, что это будет как-то быстрее по идее. Ну, не знаю, посмотрим, давай."
        assertEquals(
            "Так, окей, переключайся на Уэспербейс. Не знаю, мне кажется, что это будет как-то быстрее по идее. Ну, не знаю, посмотрим, давай.",
            ResponseCleaner.clean(raw, original),
        )
    }

    @Test
    fun `абзац с «Хотя» без служебных слов — обычный текст, не трогаем`() {
        val raw = "Я долго думал над этим.\n\nХотя, если честно, решение было очевидным с самого начала.\n\nИ я его принял."
        assertEquals(raw, ResponseCleaner.clean(raw, raw))
    }

    @Test
    fun `сомнение без второго варианта следом — не режем`() {
        val raw = "Сейчас едем в тубдиспансер.\n\nХотя, стоп — это слово не подходит по смыслу, оставлю как есть.\n\nСовсем другой абзац про погоду и дачу."
        assertEquals(raw, ResponseCleaner.clean(raw, raw))
    }

    @Test
    fun `ёлочки становятся прямыми кавычками`() {
        assertEquals("Она сказала: \"Пойдём\".", ResponseCleaner.clean("Она сказала: «Пойдём».", "она сказала пойдём"))
    }

    @Test
    fun `преамбула снимается, пустой ответ — брак`() {
        assertEquals("Привет, Наташа.", ResponseCleaner.clean("Вот исправленный текст: Привет, Наташа.", "привет наташа"))
        assertNull(ResponseCleaner.clean("   ", "привет наташа"))
    }
}
