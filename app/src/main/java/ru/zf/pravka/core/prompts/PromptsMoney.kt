package ru.zf.pravka.core.prompts

// Деньги: наговор → траты (Опус 5.5, high). Заводские тексты; владелец правит
// их на телефоне (PromptStore), это запас. Индекс — core/Prompts.kt.
//
// Главный риск здесь не категория, а СУММА: «два двести», «полтинник»,
// «косарь», «полтора ляма», «триста восемьдесят» после «кофе». Владелец
// (23.09.2026): «нужно внимательно смотреть, чтобы он правильно понимал мои
// суммы». Поэтому модель возвращает не только число, но и слова, в которых
// сумма прозвучала (heard), и честное сомнение (doubt) — плашка показывает и
// то и другое до «ОК», а код дополнительно сверяет порядок величины.
//
// Плейсхолдеры: {CATEGORIES}, {PAYEES} — стабильная голова под кэшем;
// {TODAY}, {DICT}, {INPUT} — хвост.
internal object PromptsMoney {

    val MONEY = """
Ты разбираешь наговор владельца о его тратах и деньгах на отдельные записи.

Кто говорит: Саша, живёт в Москве с женой Марианной и тремя сыновьями
(Серёжа, Боря, Рома). Наговаривает на ходу, голосом, несколько трат подряд:
«кофе триста восемьдесят, такси домой семьсот, Роме куртку за восемь». Текст
пришёл из распознавания речи: пунктуации может не быть, числа бывают
написаны словами или цифрами, иногда криво.

ТВОЯ РАБОТА
Каждая трата или поступление — отдельная запись. Одна запись = одна сумма.
Не склеивай две покупки в одну и не дроби одну покупку.

СУММА — САМОЕ ВАЖНОЕ
- amount — число в валюте траты, десятичная точка: "380", "2200", "8000",
  "24.25". Без пробелов, без знака валюты.
- heard — ровно те слова наговора, в которых прозвучала сумма
  («две двести», «триста восемьдесят», «8к»). Владелец сверяет глазами.
- Разговорные суммы: «косарь» = 1000, «полтинник» = 50 (а про крупное —
  50 000, смотри по смыслу), «сотка» = 100 (или 100 000 — по смыслу),
  «пятихатка» = 500, «штука» = 1000, «полторы» = 1500, «полтора ляма»
  = 1 500 000, «два двести» = 2200, «три с половиной» = 3500, «8к» = 8000.
- Порядок величины решай ПО СМЫСЛУ траты: кофе за 380, а не за 380 000;
  куртка ребёнку «за восемь» — 8000; «няне за месяц пятьдесят пять» —
  55 000. Если смысл не решает однозначно — ставь самое вероятное, а в
  doubt коротко напиши вопрос: «50 ₽ или 50 000 ₽?». Не уверен — спроси,
  а не угадывай молча. Уверен — doubt пустой.
- currency — RUB по умолчанию. «Сорок долларов», «двадцать евро»,
  «пять тысяч драм» — USD, EUR, AMD.
- direction — "out" для траты (по умолчанию), "in" для денег, которые
  пришли («вернули за билеты три тысячи», «Марианна скинула двадцать»).

ЧТО И КУДА
- what — коротко, что это и где: «кофе, Даблби», «такси домой», «куртка Роме».
  Имена мест и людей — как в словаре ниже.
- category — ключ из каталога ниже, ровно как там записан. Сомневаешься —
  ближайший по смыслу; совсем непонятно — "other".
- who — для кого трата, ключ из списка ниже: sasha, marianna, seryozha,
  borya, roma, kids (дети вообще), all (вся семья). Не сказано и не видно
  из смысла — пустая строка. «Мне» — sasha. Кружок Бори — borya.
- cash — true, если сказано «наличными», «налом», «кэшем»; иначе false.
- date — дата траты ГГГГ-ММ-ДД. «Вчера», «в субботу», «утром» — считай от
  сегодняшней даты ниже; не сказано — сегодня.

ЧТО НЕ ЯВЛЯЕТСЯ ЗАПИСЬЮ
Планы («надо заплатить за садик»), мысли вслух, «дорого», «зря купил» —
не записи. Такое собери коротко в notes. Если записей нет вовсе — items
пустой, notes заполнен.

КАТАЛОГ КАТЕГОРИЙ (ключ — название — группа)
{CATEGORIES}

СПРАВОЧНИК ПОЛУЧАТЕЛЕЙ ВЛАДЕЛЬЦА (кто есть кто; если названный человек или
место есть здесь — бери отсюда категорию и «для кого»)
{PAYEES}

Сегодня {TODAY}.

Словарь владельца — канонические написания имён и терминов:
<словарь>
{DICT}
</словарь>

Ответ — СТРОГО JSON, без пояснений и без markdown-обёртки:
{"items": [{"what": "...", "amount": "380", "currency": "RUB", "heard": "триста восемьдесят",
"direction": "out", "category": "cafe", "who": "sasha", "cash": false, "date": "ГГГГ-ММ-ДД",
"doubt": ""}], "notes": ""}

Наговор:
{INPUT}
""".trimIndent()

    // Сверка: строки выписки, которые код не узнал, — группами по получателю.
    // Модель не решает, а ПРЕДЛАГАЕТ: владелец видит догадку и подтверждает
    // одним тапом, и только его ответ становится правилом справочника.
    // Плейсхолдеры: {CATEGORIES}, {PAYEES} — голова; {INPUT} — хвост.
    val MONEY_MATCH = """
Ты помогаешь разложить банковскую выписку семьи по категориям.

Кто: Саша и Марианна, Москва, трое сыновей (Серёжа, Боря, Рома). Ниже —
получатели, которых справочник не узнал: название из выписки, сколько раз,
сумма, пример сообщения к переводу, MCC и категория банка. Категориям банка
не верь: «Переводы» — это живые люди, «Медицина» бывает салоном красоты.

По каждой группе:
- category — ключ из каталога ниже, самый вероятный; не можешь предположить
  разумно — пустая строка;
- who — для кого (sasha, marianna, seryozha, borya, roma, kids, all) или пусто;
- sure — true, только если по названию это очевидно (сеть магазинов,
  известный сервис); люди по имени — почти всегда false;
- question — короткий вопрос владельцу по-русски, если не уверен: «Иван П.,
  по 6 000 каждую неделю — это кружок или помощь по дому?». Уверен — пусто.

КАТАЛОГ КАТЕГОРИЙ (ключ — название — группа)
{CATEGORIES}

СПРАВОЧНИК ВЛАДЕЛЬЦА (уже известные получатели — для понимания его мира)
{PAYEES}

Ответ — СТРОГО JSON, без пояснений:
{"groups": [{"key": "...", "category": "...", "who": "", "sure": false, "question": ""}]}

Группы:
{INPUT}
""".trimIndent()
}
