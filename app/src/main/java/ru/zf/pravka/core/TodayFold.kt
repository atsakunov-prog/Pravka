package ru.zf.pravka.core

// Когда шапка «Сегодня» сжата (Правка 4.0, DESIGN §11.2): развёрнута, пока
// «сейчас» видно в окне или выше него; сжимается, когда «сейчас» ушло ниже
// окна — смотрим прошлое.
//
// Баг №2 (07.10.2026, владелец: «когда крутишь в „сегодня“, и оно доходит до
// „сейчас“ с сокращённого, то оно пытается открыться сверху до подробного, но
// не может, и так вот прыгает»). Причина — у правила не было памяти: сжатая
// шапка ниже на ~230 dp, окно ленты выше, «сейчас» в него попадает —
// шапка разворачивается, окно сжимается, «сейчас» снова за краем — шапка
// сжимается… Теперь развернуться можно, только если «сейчас» останется
// видно и ПОСЛЕ разворота: оно должно стоять выше нижнего края хотя бы на
// высоту, которую шапка заберёт ([grow]). Между порогами — прежнее состояние.
// С 07.10 (баг №18) высоту шапки гасит прокрутка ленты (`TodayScreen`), и
// «сейчас» при развороте на экране не двигается; [grow] тогда — только запас
// от дрожи, полная высота — лишь когда ленте некуда прокручиваться.

object TodayFold {

    /**
     * Где лента сейчас. Положения — в пикселях от начала окна ленты; [viewEnd]
     * — нижний край того, что видно глазом (без поля под строкой «сказать»).
     * [nowTop]/[nowBottom] — края строки «сейчас», если она выложена, иначе null.
     */
    data class View(
        val first: Int,
        val firstOffset: Int,
        val last: Int,
        val nowTop: Int?,
        val nowBottom: Int?,
        val viewEnd: Int,
    )

    /**
     * Следующее состояние шапки: true — сжата. [nowIndex] — строка «сейчас»
     * в ленте (−1 — её нет: прошлый или будущий день), [today] — смотрим
     * сегодняшний день (в другом дне шапка сама не сжимается: в ней
     * навигатор дня), [grow] — на сколько пикселей развёрнутая шапка выше
     * сжатой.
     */
    fun next(compact: Boolean, nowIndex: Int, v: View, grow: Int, today: Boolean): Boolean {
        if (!today) return false
        if (nowIndex < 0) {
            // Дня без «сейчас» на сегодня не бывает, но и тут без дрожи:
            // сжимаемся, уйдя с первой строки, разворачиваемся — вернувшись в самое начало.
            return if (compact) !(v.first == 0 && v.firstOffset == 0) else v.first > 0
        }
        val below = nowIndex > v.last || (v.nowTop != null && v.nowTop >= v.viewEnd)
        if (below) return true
        val above = nowIndex < v.first || (v.nowBottom != null && v.nowBottom <= 0)
        if (above) return false
        if (!compact) return false
        // Видно, шапка сжата: развернуться — только если «сейчас» не уйдёт за край.
        val bottom = v.nowBottom ?: return true
        return bottom > v.viewEnd - grow
    }
}
