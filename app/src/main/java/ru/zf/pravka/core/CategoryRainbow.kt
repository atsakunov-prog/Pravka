package ru.zf.pravka.core

import kotlin.math.abs

/**
 * Радуга владельца: у каждой категории своё место на спектре по тому, насколько
 * хорошо потрачен час. Работа и учёба горят красным, спорт оранжевый, люди —
 * тёплые зелёные, восстановление и логистика остывают через голубой к синему,
 * чистый досуг и потери падают в фиолетовый. Оттенок закреплён за именем; новая
 * категория, которую владелец заведёт позже, получает устойчивое место по хешу.
 *
 * Живёт в core, а не во вкладке, потому что радуга — не только цвет: по ней
 * сортируются итоги Засечки (красная работа сверху, потери внизу) и по ней же
 * раскладывается донат дня в «Отчёте». Два списка оттенков разъехались бы за
 * неделю; сама заливка (яркость под тему) остаётся делом вкладки.
 */
object CategoryRainbow {

    private val HUES = mapOf(
        "работа: привлечение" to 0f,
        "работа: текущая" to 8f,
        "работа: планирование" to 16f,
        "работа: звонки" to 24f,
        "чтение" to 32f,
        "систематизация" to 40f,
        "спорт: силовая" to 48f,
        "спорт: бег" to 56f,
        "спорт: вело" to 64f,
        "спорт: прочее" to 72f,
        "семья" to 88f,
        "секс: с марианной" to 100f,
        "социальное: внешнее" to 118f,
        "звонки" to 135f,
        "сон" to 155f,
        "еда" to 170f,
        "передвижение: пешком" to 190f,
        "передвижение: вело" to 205f,
        "передвижение: транспорт" to 220f,
        "быт" to 235f,
        "отдых" to 262f,
        "секс: соло" to 278f,
        // Старое имя v1/v2, ещё живое на устройстве, — рядом с «соло».
        "секс" to 278f,
        // Самый низ спектра: время, потраченное ни на что.
        // («прокрастинация» прожила одну сборку до переименования.)
        "потери" to 292f,
        "не размечено" to 292f,
        "прокрастинация" to 292f,
    )

    /** Место на радуге эффективности, 0 (красный) .. 292 (фиолетовый). */
    fun hue(name: String): Float {
        val key = name.trim().lowercase()
        return HUES[key] ?: (abs(key.hashCode()) % 281).toFloat()
    }
}
