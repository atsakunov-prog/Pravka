package ru.zf.pravka.core

/**
 * Подпись шапки вида v2 — переносом по словам, а не «…» (владелец 14.10.2026: «где-то можно переносить по
 * словам»). Строка шапки — это куски через « · » («ср, 14 окт · 18:50 · очки +84»), и на сложенном Fold она
 * не всегда влезает в одну строку рядом со значками. Перенос обычный, по пробелам, но с двумя правилами, чтобы
 * вторая строка читалась:
 *
 * - число не отрывается от своего слова: «очки +84», «3 сегодня», «14 октября», «2 ч 2 м» — неразрывным
 *   пробелом. Склеиваются только пары с числом, длинный кусок без чисел («телефон и компьютер», заголовок
 *   страницы сервиса) переносится как обычно — иначе в узкой шапке он рвался бы по буквам;
 * - точка-разделитель остаётся в конце строки, а не начинает следующую: пробел перед « · » неразрывный.
 */
object HeadLine {

    /** Неразрывный пробел: ICU по нему не переносит (класс GL). */
    const val NBSP = ' '

    // Пробел после « · » — место переноса: число за ним к предыдущему куску не клеится.
    private val beforeNumber = Regex("(?<!·) (?=[+\\-${Fmt.MINUS}]?\\d)")
    private val afterNumber = Regex("(?<=\\d) (?=[^·])")
    private val beforeDot = Regex(" ·")

    fun wrap(s: String): String = s
        .replace(beforeNumber, NBSP.toString())
        .replace(afterNumber, NBSP.toString())
        .replace(beforeDot, "$NBSP·")
}
