package ru.zf.pravka.core

/**
 * Страховка от потерянного отрицания (12.10.2026). Ночной разбор ещё 18.09
 * насчитал восемь удалений «не» за неделю — не заикание, а смена смысла на
 * противоположный: «бежал столько, что не… мог бы» → «что уже мог бы»,
 * «Нет, это наша общая встреча» → «Михаил, это наша общая встреча». Для
 * диктовки людям это худшая ошибка из возможных, а ловится она без модели:
 * отрицаний в ответе меньше, чем в надиктованном, — значит, одно потеряно.
 * Владелец: «всё должно идти автоматом» — поэтому не предупреждение, а один
 * повтор чистки с указанием (`ProofreadEngine`).
 *
 * Чего не считаем потерей: повтор подряд («не не надо», «нет, нет, нет», «я не
 * знаю, я не знаю», в том числе через «э») — его модель убирает законно
 * (правило про повторы); слитное написание («не правильно» → «неправильно») —
 * отрицание на месте, это орфография.
 */
object NegationGuard {

    private val NEG = setOf("не", "нет", "ни", "нельзя")
    /** Звуки раздумья — прозрачны для повтора: «не э не знаю» — одно «не». */
    private val FILLERS = setOf("э", "ээ", "эээ", "эм", "мм", "ммм", "хм")
    /** Самый длинный повтор группы слов, который модель вправе схлопнуть. */
    private const val MAX_REPEAT = 6
    private val WORD = Regex("[\\p{L}\\p{N}]+")
    private val SEPARATE_NE = Regex("(?<![\\p{L}\\p{N}])не\\s+(\\p{L}+)")

    private fun words(text: String): List<String> =
        WORD.findAll(text.lowercase().replace('ё', 'е')).map { it.value }.toList()

    /** Сколько отрицаний в тексте; повтор подряд (слово или группа слов) — один раз. */
    fun count(text: String): Int = collapse(words(text).filter { it !in FILLERS }).count { it in NEG }

    /** Схлопнуть повторы подряд: «я не знаю я не знаю» → «я не знаю», «не не» → «не». */
    private fun collapse(words: List<String>): List<String> {
        val out = ArrayList<String>(words.size)
        for (w in words) {
            out.add(w)
            // Хвост совпал с предыдущим куском той же длины — снять копию.
            for (k in 1..MAX_REPEAT) {
                if (out.size < 2 * k) break
                val n = out.size
                if ((0 until k).all { out[n - k + it] == out[n - 2 * k + it] }) {
                    repeat(k) { out.removeAt(out.size - 1) }
                    break
                }
            }
        }
        return out
    }

    /** Сколько отрицаний надиктованного не дошло до ответа (0 — всё на месте). */
    fun lost(input: String, output: String): Int {
        val outWords = words(output).toSet()
        // «не правильно» в диктовке и «неправильно» в ответе — то же отрицание.
        val merged = SEPARATE_NE.replace(input.lowercase().replace('ё', 'е')) { m ->
            if ("не" + m.groupValues[1] in outWords) "не" + m.groupValues[1] else m.value
        }
        return (count(merged) - count(output)).coerceAtLeast(0)
    }

    /** Указание для повтора — едет директивой в некэшируемом слоте, префикс промпта не трогает. */
    fun retryDirective(input: String): String =
        "ПРОВЕРКА ОТРИЦАНИЙ. В надиктованном тексте отрицаний («не», «нет», «ни», «нельзя») — ${count(input)}, " +
            "а в твоей прошлой чистке их оказалось меньше: одно потеряно, и смысл перевернулся. Сохрани каждое " +
            "отрицание из диктовки на его месте и не превращай «нет» в обращение или другое слово. Убирать можно " +
            "только повтор подряд («не не», «нет, нет»). Остальное — как обычно."
}
