package ru.zf.pravka.core

// Одна позиция в тарелке — то, что вернула модель (или база по штрихкоду) и
// что владелец правит руками. Живёт в core рядом с ParsedTask по той же
// причине: её отдаёт провайдер, а хранит стор, и своего типа у каждого из них
// быть не должно.
//
// Все числа — на ВСЮ порцию, а не на 100 г, и целые: дневник еды не то место,
// где нужна точность до десятой грамма белка.
data class MealItem(
    val name: String,
    val grams: Int,
    val kcal: Int,
    val protein: Int,
    val fat: Int,
    val carbs: Int,
    val fiber: Int = 0,
    // Насколько цифрам можно верить: «точно» (упаковка или штрихкод),
    // «примерно» (продукт понятен, порция на глаз), «наугад» (составное
    // незнакомое блюдо). Пустая строка = модель не сказала.
    val sureness: String = "",
    /**
     * Витамины и элементы на всю порцию: ключ справочника
     * (`Micronutrients.Nutrient.id`) → количество в единице этого вещества.
     *
     * Карта РАЗРЕЖЕННАЯ и такой задумана: пишем только заметное, от десятой
     * нормы. Нули по девятнадцати веществам в каждой позиции раздули бы и
     * ответ модели, и дневник на диске, а сказали бы ровно то же самое, что
     * их отсутствие.
     */
    val micro: Map<String, Double> = emptyMap(),
    /**
     * Это таблетка, а не еда. Отметка стоит на ПОЗИЦИИ, а не на приёме:
     * «позавтракал и выпил витамин D» — один завтрак, в котором одна позиция
     * из банки, и только так видно, что кальций пришёл из творога, а магний
     * из аптеки.
     */
    val pill: Boolean = false,
) {
    /** Сходятся ли калории с макросами: 4/9/4 с допуском. */
    fun kcalFromMacros(): Int = protein * 4 + fat * 9 + carbs * 4

    /**
     * Пересчёт позиции на другой вес — этим правят порцию руками, не заставляя
     * модель считать заново. Ноль граммов в исходной позиции пересчитать
     * нельзя (не от чего), поэтому она возвращается как есть.
     */
    fun scaledTo(newGrams: Int): MealItem {
        if (grams <= 0 || newGrams <= 0) return this
        val k = newGrams.toDouble() / grams
        return copy(
            grams = newGrams,
            kcal = Math.round(kcal * k).toInt(),
            protein = Math.round(protein * k).toInt(),
            fat = Math.round(fat * k).toInt(),
            carbs = Math.round(carbs * k).toInt(),
            fiber = Math.round(fiber * k).toInt(),
            // Витамины едут за весом так же, как калории: съел вдвое больше
            // творога — вдвое больше и кальция.
            micro = Micronutrients.scaleBy(micro, k),
        )
    }

    companion object {
        /**
         * Вид приёма. «Добавки» — пятый и особенный: это не еда, а горсть
         * таблеток («выпил витамин D две тысячи и магний»). Калорий в ней
         * нет, в ленту она не приписывается, а в сутки идёт только веществами.
         */
        const val SUPPLEMENT = "добавки"

        val KINDS = listOf("завтрак", "обед", "ужин", "перекус", SUPPLEMENT)

        /** Вид приёма по времени суток — когда владелец его не назвал. */
        fun kindByHour(hour: Int): String = when (hour) {
            in 0..3 -> "перекус"
            in 4..11 -> "завтрак"
            in 12..16 -> "обед"
            in 17..22 -> "ужин"
            else -> "перекус"
        }
    }
}
