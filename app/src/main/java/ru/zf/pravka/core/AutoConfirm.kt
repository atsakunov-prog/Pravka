package ru.zf.pravka.core

/**
 * Плашка с «ОК» молчанием соглашается (владелец, 26.09.2026: «не нажал
 * ничего = подтвердил. А то я буду наговаривать и думать, что это куда-то
 * ушло, а это, например, никуда не уйдёт»).
 *
 * Раньше плашка еды по фото, дел из чужого текста и трат через 45 секунд
 * тихо уходила, а разобранное оставалось ждать «ОК» во вкладке — ровно та
 * потеря, которую он описал: наговорил, отвлёкся, плашки нет, записи тоже.
 * Теперь уйти без ответа — значит ответить «да», и сколько осталось, видно
 * на самой плашке. «Нет» — это «✕»: его надо нажать.
 */
object AutoConfirm {

    /** Короче не бывает: прочитать одну строку и дотянуться до «✕». */
    const val MIN_HOLD_MS = 15_000L

    /** Дольше не бывает: плашка висит поверх чужого экрана. */
    const val MAX_HOLD_MS = 45_000L

    /** Каждая строка — ещё немного чтения. */
    private const val BASE_MS = 9_000L
    private const val PER_ROW_MS = 3_000L

    /** Сколько плашка ждёт ответа при [rows] строках на ней. */
    fun holdMs(rows: Int): Long =
        (BASE_MS + PER_ROW_MS * rows.coerceAtLeast(1)).coerceIn(MIN_HOLD_MS, MAX_HOLD_MS)

    /**
     * Секунды на плашке — с округлением вверх: «1» держится до самого
     * конца, а «0» не показывается — в этот миг плашка уже соглашается.
     */
    fun secondsLeft(remainingMs: Long): Int =
        if (remainingMs <= 0) 0 else ((remainingMs + 999) / 1000).toInt()

    /** «Запишу сам через 12 с». */
    fun line(verb: String, remainingMs: Long): String = "$verb через ${secondsLeft(remainingMs)} с"
}
