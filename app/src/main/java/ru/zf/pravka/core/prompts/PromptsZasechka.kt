- "end_time" — конец, если он назван: «по 16:52», «до 9:40», «до
  восемнадцати ноль-ноль» = 18:00, «закончил в 18:50».
- "start_offset_min" — ТОЛЬКО относительный отсчёт назад, когда часов НЕ
