package ru.zf.pravka.core

import kotlin.math.abs
import kotlin.math.max
import kotlin.math.min

/**
 * Свечение режима во вкладке (версия 3, 26.09.2026) — числами, без Android,
 * под JVM-тестом. Рисует по ним `ui/Glow.kt`.
 *
 * Владелец, увидев первый макет, где к цвету режима подмешивались чужие цвета
 * (к оранжевому — малиновый и золото): «сохраним цветность каждого
 * направления». Второй заход в тот же вечер: «не очень яркое, какое-то слишком
 * равномерное… должно как-то двигаться… наверху свечение какое-то круглое…
 * серые плашки выглядят не очень».
 *
 * Третий заход (27.09.2026), со снимками: «с края просто едет такая тёмная
 * резкая полоса… может, чуть сделать переливы динамические с чуть соседними
 * цветами. И давай точнее сделаем главные цвета как на кнопках, они там прямо
 * классные. И поярче сделаем сами переливы, грустно как-то». Отсюда:
 *
 * - главный тон [tone] — РОВНО цвет кнопки режима на стекле. Прежде тёмные
 *   чернила зажигались до яркости 0,92, и синий «Д» становился голубым, а
 *   изумрудный «Т» — неоновой мятой: не тот цвет, что на кнопке;
 * - перелив — СОСЕДНИЕ оттенки: [warm] на [NEIGHBOR_DEG] градусов в одну
 *   сторону круга и светлее, [cool] — на столько же в другую. Не чужие цвета
 *   (малинового у оранжевого нет), а тот же цвет, повёрнутый на полшага; они
 *   переливаются друг в друга ([SHIMMER_MS]), и глаз видит, что свет живой;
 * - ярче — не выцветанием, а насыщенностью: соседи насыщеннее кнопки
 *   ([NEIGHBOR_SAT]), блик [lit] почти не теряет цвет. Бледный тон на ночи
 *   читается серой дымкой — «блёкло», «грустно».
 */
object ModeGlow {

    /** Сила свечения с завода (ползунок «Свечение режима», 0 — выключено). */
    const val DEFAULT = 0.9f

    /** Пока Claude работает во вкладке, свет ярче — один плавный переход, без мерцания. */
    const val BUSY_BOOST = 1.2f

    /** Как долго свет меняет силу, мс: дольше — не успевает за ответом, короче — вспышка. */
    const val FADE_MS = 700

    /** Мерка пятен — ширина экрана, но не шире [MAX_HEIGHT_DP]: на развороте Fold не заливать полэкрана. */
    const val MAX_HEIGHT_DP = 460

    /** Самая яркая точка — при силе 1. */
    const val PEAK = 1f

    /**
     * На сколько градусов круга соседние тона отходят от цвета кнопки. Меньше
     * восьми перелив не видно, больше двадцати — это уже другой цвет (у
     * оранжевого «П» — красный и жёлтый), а владелец просил «чуть соседними».
     */
    const val NEIGHBOR_DEG = 14f

    /** Во сколько раз соседние тона насыщеннее кнопки (до предела): ярче без выцветания. */
    const val NEIGHBOR_SAT = 1.1f

    /**
     * Период, за который пятно света обходит свою петлю, мс. У пятен
     * периоды разные и не кратные ([DRIFT_MS] × 1; 1,37; 1,71; 2,13): рисунок
     * не повторяется на глазах и читается живым, а не качелями. Медленно
     * нарочно — пульсацию кнопки владелец снял («дрожание отвлекает»).
     */
    const val DRIFT_MS = 17_000

    /** Насколько далеко плывёт пятно — доля мерки (ширины экрана). */
    const val DRIFT = 0.1f

    /** Период перелива соседних тонов друг в друга, мс. */
    const val SHIMMER_MS = 11_000

    /**
     * Размах перелива: соседнее пятно дышит от (1 − SHIMMER) до 1 своей силы,
     * и два соседа — навстречу друг другу: пока светлеет тёплый, гаснет
     * холодный, и цвет верха медленно поворачивается туда и обратно.
     */
    const val SHIMMER = 0.45f

    /** Альфа главного пятна при силе [strength] (0..1). */
    fun alpha(strength: Float, busy: Boolean): Float {
        val s = strength.coerceIn(0f, 1f)
        if (s <= 0f) return 0f
        return min(PEAK, s * (if (busy) BUSY_BOOST else 1f) * PEAK)
    }

    /** Главный тон — ровно цвет кнопки режима на стекле. */
    fun tone(accent: Int): Int = accent or (0xFF shl 24)

    /** Тёплый сосед — на [NEIGHBOR_DEG] по кругу вперёд, насыщеннее и светлее кнопки. */
    fun warm(accent: Int): Int {
        val (h, s, v) = hsv(accent)
        return fromHsv(h + NEIGHBOR_DEG, min(1f, s * NEIGHBOR_SAT), min(1f, v * 1.35f + 0.05f))
    }

    /** Холодный сосед — на [NEIGHBOR_DEG] назад, насыщеннее, яркость почти кнопкина. */
    fun cool(accent: Int): Int {
        val (h, s, v) = hsv(accent)
        return fromHsv(h - NEIGHBOR_DEG, min(1f, s * NEIGHBOR_SAT), min(1f, v * 1.1f))
    }

    /**
     * Блик — тот же оттенок, что кнопка, на полпути к полному свету и почти
     * той же насыщенности: как светлая верхушка кнопки под бликом стекла.
     */
    fun lit(accent: Int): Int {
        val (h, s, v) = hsv(accent)
        return fromHsv(h, s * 0.92f, min(1f, v + (1f - v) * 0.5f))
    }

    /**
     * Плашка вкладки — стекло в тех же чернилах, что пилюля диктовки
     * ([PillLook.INK]): сверху слева в чернила подмешан цвет кнопки, книзу
     * справа — почти одни чернила. Прежняя плашка — ровный тёмный тон краски
     * (насыщенность 0,5, яркость 0,25) — читалась бурой у оранжевой Правки и
     * «что-то с плашками надо сделать» (27.09.2026); у пилюли тот же цвет в
     * чернилах владельцу нравился с первого дня.
     */
    fun cardTop(accent: Int): Int = PillLook.mix(accent or (0xFF shl 24), PillLook.INK, CARD_INK_TOP)

    fun cardBottom(accent: Int): Int = PillLook.mix(accent or (0xFF shl 24), PillLook.INK, CARD_INK_BOTTOM)

    /** Доля чернил в плашке: сверху цвета больше, книзу — почти нет. */
    const val CARD_INK_TOP = 0.78f
    const val CARD_INK_BOTTOM = 0.93f

    // ---- HSV без android.graphics.Color: числа должны проверяться на JVM ----

    data class Hsv(val h: Float, val s: Float, val v: Float)

    fun hsv(color: Int): Hsv {
        val r = (color shr 16 and 0xFF) / 255f
        val g = (color shr 8 and 0xFF) / 255f
        val b = (color and 0xFF) / 255f
        val mx = max(r, max(g, b))
        val mn = min(r, min(g, b))
        val d = mx - mn
        val h = when {
            d == 0f -> 0f
            mx == r -> 60f * (((g - b) / d) % 6f)
            mx == g -> 60f * ((b - r) / d + 2f)
            else -> 60f * ((r - g) / d + 4f)
        }.let { if (it < 0f) it + 360f else it }
        val s = if (mx == 0f) 0f else d / mx
        return Hsv(h, s, mx)
    }

    fun fromHsv(h: Float, s: Float, v: Float): Int {
        val hh = ((h % 360f) + 360f) % 360f
        val c = v * s
        val x = c * (1f - abs((hh / 60f) % 2f - 1f))
        val m = v - c
        val (r, g, b) = when {
            hh < 60f -> Triple(c, x, 0f)
            hh < 120f -> Triple(x, c, 0f)
            hh < 180f -> Triple(0f, c, x)
            hh < 240f -> Triple(0f, x, c)
            hh < 300f -> Triple(x, 0f, c)
            else -> Triple(c, 0f, x)
        }
        fun ch(f: Float) = ((f + m) * 255f + 0.5f).toInt().coerceIn(0, 255)
        return (0xFF shl 24) or (ch(r) shl 16) or (ch(g) shl 8) or ch(b)
    }
}
