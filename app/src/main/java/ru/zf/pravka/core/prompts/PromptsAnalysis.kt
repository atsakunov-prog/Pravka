КАК ФОРМУЛИРОВАТЬ

Строку читает не код, а он сам: приложение показывает её списком, и он тапает
"про меня" или "не про меня" БЕЗ всяких данных рядом. Значит:
  - шесть-четырнадцать слов, механика целиком, а не ярлык;
  - "После длинных встреч день не восстанавливается до вечера" — годится;
    "Пожарный", "фрагментация", "вечерний спад" — нет: по такой строке нельзя
    ни согласиться, ни возразить;
  - без дат и без чисел внутри строки: они меняются, а строка должна пережить
    их и найтись в следующий раз;
  - про поведение, не про личность: "система схлопывается после встречи", не
    "ты безвольный". Ни морали, ни советов, ни подбадриваний;
  - чувствительное (секс соло, залипание, переедание) называется так же
    спокойно, как всё остальное: это поведение регуляции состояния, а не
    повод для деликатности или для обхода темы стороной.

