package ru.zf.pravka.core

/**
 * Сделанное стоит на месте (отладка 16.10.2026 вечер, запись 30). Владелец: «когда выполняю дело — нажимаю на флажок, а
 * текст в колонке прыгает, будто перерисовывается, и я промахиваюсь и кликаю на другое».
 *
 * Почему прыгало: флажок кладёт `task.done` в очередь, копия поверх очереди (`Dela.overlay`) закрывает дело сразу, а
 * списки («Сейчас», «Сегодня», группы «Всех дел») берут только открытые — строка исчезала в тот же кадр, и всё ниже
 * поднималось на её высоту под пальцем. Пустела группа — уходила и вся её карточка.
 *
 * Как теперь: дело, закрытое флажком, вкладка «держит» — списки считают его по той копии, какой оно было до касания
 * (то же место, та же группа, тот же порядок), а строка рисуется сделанной: залитый флажок, зачёркнутое название
 * (повторный тап — «Вернуть в работу», как раньше). Уходит строка, когда списком не трогали [HOLD_MS], или при
 * следующей смене экрана (раздел, страница, сфера, поиск). Держит только вкладка, в памяти: сервер, синк и другие
 * экраны видят дело сделанным сразу.
 */
object DelaLinger {

    /** Сколько сделанная строка стоит на месте, пока списка не касаются. */
    const val HOLD_MS = 4_000L

    /**
     * Копия для списков: дела из [held] (id → каким было до «Сделано»), которые живая копия уже закрыла, — прежними,
     * открытыми. Вернул в работу (живое снова открыто) или дела больше нет — живое как есть.
     */
    fun view(s: Dela.Snapshot, held: Map<String, Dela.Task>): Dela.Snapshot {
        if (held.isEmpty()) return s
        var tasks: LinkedHashMap<String, Dela.Task>? = null
        for ((id, before) in held) {
            val live = s.tasks[id] ?: continue
            if (live.open || !before.open) continue
            if (tasks == null) tasks = LinkedHashMap(s.tasks)
            tasks[id] = before
        }
        return if (tasks == null) s else s.copy(tasks = tasks)
    }

    /** Строки, которые стоят на месте сделанными: держим, а живая копия их уже закрыла. */
    fun doneHere(held: Map<String, Dela.Task>, live: Dela.Snapshot): Set<String> =
        held.keys.filterTo(HashSet()) { live.tasks[it]?.open == false }

    /**
     * Тап по флажку строки [live] (дело как оно есть сейчас): открытое — закрывается и встаёт держаться прежним; уже
     * закрытое — возвращается в работу и держать его незачем.
     */
    fun tap(held: Map<String, Dela.Task>, live: Dela.Task): Map<String, Dela.Task> =
        if (live.open) held + (live.id to live) else held - live.id

    /** Сколько ещё держать после последнего касания [lastTouch]; 0 — пора отпускать. */
    fun left(lastTouch: Long, now: Long): Long = (lastTouch + HOLD_MS - now).coerceAtLeast(0L)
}
