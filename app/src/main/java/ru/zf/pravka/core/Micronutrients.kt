/**
 * Витамины и элементы: справочник норм, пределов и объяснений — один на всё
 * приложение.
 *
 * Зачем он вообще. КБЖУ отвечает на вопрос «сколько», но не на вопрос «из
 * чего»: можно месяцами попадать в 2500 ккал и 160 г белка и при этом сидеть
 * на трети нормы магния и половине нормы витамина D — в Москве с ноября по
 * март на ней сидят все. Такое видно только накопительно, поэтому вещества
 * считаются так же, как калории: по позициям, за сутки, с нормой.
 *
 * Числа — рекомендуемые суточные нормы для мужчины 31–50 лет (US RDA/AI, где
 * их нет — EFSA). Верхний предел (UL) — не «смерть», а граница, выше которой
 * регулярно ходить незачем; с таблетками её перейти легко, поэтому она здесь
 * и есть. У натрия всё наоборот: норма — это ПОТОЛОК ([limit]), и полоска
 * зелёная, пока он не добран, а не когда добран.
 *
 * «Зачем» рядом с каждым веществом — не украшение: цифра «60 % нормы цинка»
 * ничего не решает, а «цинк — тестостерон, иммунитет и заживление, уходит с
 * потом» решает. Владелец: «по каждому витамину внизу так чуть-чуть написано,
 * зачем он».
 *
 * Ключи ([Nutrient.id]) короткие и стабильные: ими говорит модель в JSON,
 * ими лежат числа в дневнике на диске. Переименовывать их нельзя — старые
 * приёмы читаются по ним.
 *
 * Файл без Android: его проверяет JVM-тест.
 */
object Micronutrients {

