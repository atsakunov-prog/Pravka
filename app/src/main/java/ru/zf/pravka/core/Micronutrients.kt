    const val MINERALS = "минералы"
    const val OTHER = "прочее"

    data class Nutrient(
        /** Короткий ключ в JSON и на диске: «vd», «ca», «o3». Не переименовывать. */
        val id: String,
        val name: String,
        /** мкг | мг | г — в ней же считаются все количества этого вещества. */
        val unit: String,
        /** Суточная норма. У [limit]-веществ это потолок, а не цель. */
        val norm: Double,
        /** Верхний предел за сутки; 0 — не установлен (перебором не пугаем). */
        val ceiling: Double,
        /** Зачем он нужен — одной фразой, под полоской. */
        val why: String,
        /** Где брать едой — вторая половина той же фразы. */
        val source: String,
        val group: String,
        /** Норма — это потолок: чем меньше, тем лучше (натрий). */
        val limit: Boolean = false,
    ) {
        /** Доля нормы: 1.0 — ровно норма. Норма 0 не бывает, но делить на неё нельзя. */
        fun share(value: Double): Double = if (norm <= 0) 0.0 else value / norm

        /**
         * Предел полоски. Норма стоит ЗАСЕЧКОЙ внутри, а не в конце: перебор
         * (а с таблетками он реален) должен быть виден, а не упираться в край.
         */
        fun scale(): Double = when {
            limit && ceiling > 0 -> ceiling * 1.15
            ceiling > 0 -> minOf(norm * 1.5, ceiling * 1.05)
            else -> norm * 1.5
        }
    }

    /** Светофор полоски: мало · средне · достаточно · перебор. */
    enum class Level { LOW, MID, OK, OVER }

    /** Светофор словами — одинаково на экране, в Notion и в книге Excel. */
    fun word(level: Level): String = when (level) {
        Level.LOW -> "мало"
        Level.MID -> "средне"
        Level.OK -> "достаточно"
        Level.OVER -> "перебор"
    }

    // Пороги светофора. Половина нормы — «мало» не по вкусу: ниже неё дефицит
    // перестаёт быть арифметикой и начинает быть симптомом. От 80 % — уже
    // «достаточно»: суточная норма сама по себе среднее с запасом, и требовать
    // ровно 100 % каждый день значило бы светить красным вечно.
    private const val LOW_UNDER = 0.5
    private const val OK_FROM = 0.8

    fun level(n: Nutrient, value: Double): Level {
        if (n.limit) {
            // Натрий: ниже нормы — хорошо, выше предела — плохо.
            return when {
                n.ceiling > 0 && value > n.ceiling -> Level.OVER
                value > n.norm -> Level.MID
                else -> Level.OK
            }
        }
        val share = n.share(value)
        return when {
            n.ceiling > 0 && value > n.ceiling -> Level.OVER
            share < LOW_UNDER -> Level.LOW
            share < OK_FROM -> Level.MID
            else -> Level.OK
        }
    }

