    private val BY_ID: Map<String, Nutrient> = ALL.associateBy { it.id }

    fun byId(id: String): Nutrient? = BY_ID[id.trim().lowercase()]

    /** Порядок вещества в справочнике: по нему сортируются колонки и полоски. */
    fun order(id: String): Int = ALL.indexOfFirst { it.id == id }

    // ---- Арифметика ----

    /**
     * Сложить карты веществ нескольких позиций. Неизвестные ключи выбрасываются
     * молча: модель иногда называет вещество, которого в справочнике нет
     * («хром», «холин»), и падать из-за этого незачем — но и считать тоже.
     */
    fun sum(maps: Iterable<Map<String, Double>>): Map<String, Double> {
        val out = LinkedHashMap<String, Double>()
        for (map in maps) {
            for ((rawId, value) in map) {
                val n = byId(rawId) ?: continue
                if (value <= 0) continue
                out[n.id] = (out[n.id] ?: 0.0) + value
            }
        }
        return out
    }

    /** Умножить все количества на коэффициент — пересчёт позиции на другой вес. */
    fun scaleBy(map: Map<String, Double>, k: Double): Map<String, Double> {
        if (map.isEmpty() || k == 1.0) return map
        val out = LinkedHashMap<String, Double>(map.size)
        for ((id, v) in map) out[id] = v * k
        return out
    }

    /**
     * Оставить только заметное — от десятой нормы. Полоска в 3 % нормы это не
     * данные, а шум: такие числа модель выдаёт наугад, а место на экране и в
     * таблице они занимают всерьёз.
     */
    const val NOTABLE_SHARE = 0.1

    fun notable(map: Map<String, Double>): Map<String, Double> =
        map.filter { (id, v) -> byId(id)?.let { v >= it.norm * NOTABLE_SHARE } == true }

    /** Чего за день меньше половины нормы — словами, для таблицы и записки. */
    fun lacking(totals: Map<String, Double>): List<Nutrient> =
        ALL.filter { !it.limit && level(it, totals[it.id] ?: 0.0) == Level.LOW }

    /** Чего вышло за верхний предел — там же. */
    fun over(totals: Map<String, Double>): List<Nutrient> =
        ALL.filter { level(it, totals[it.id] ?: 0.0) == Level.OVER }

    // ---- Числа словами ----

    /**
     * Количество для глаз: мелкое — с десятой, крупное — целым. 1,3 мг B6 и
     * 3400 мг калия в одной колонке иначе выглядят одинаково нелепо.
     */
    fun amount(value: Double): String {
        val v = if (value < 0) 0.0 else value
        return when {
            v >= 100 -> String.format(Locale.US, "%.0f", v)
            v >= 10 -> String.format(Locale.US, "%.0f", v)
            v >= 1 -> trim(String.format(Locale.US, "%.1f", v))
            else -> trim(String.format(Locale.US, "%.2f", v))
        }
    }

    private fun trim(s: String): String =
        s.trimEnd('0').trimEnd('.').ifBlank { "0" }.replace('.', ',')

    /** «Витамин D 50 мкг · Магний 300 мг» — для записки, ленты и таблицы. */
    fun short(map: Map<String, Double>, limit: Int = 6): String =
        map.entries
            .mapNotNull { (id, v) -> byId(id)?.let { it to v } }
            .sortedBy { order(it.first.id) }
            .take(limit)
            .joinToString(" · ") { (n, v) -> "${n.name} ${amount(v)} ${n.unit}" }

    /**
     * Блок для промпта: ключи, названия, единицы и нормы. Уезжает в стабильную
     * (кэшируемую) голову промпта — он не меняется от запроса к запросу.
     */
    fun promptBlock(): String = buildString {
        append("Ключи веществ (пиши ровно эти ключи, количества — на ВСЮ порцию, в указанной единице):\n")
        for (n in ALL) {
            append("- ").append(n.id).append(" — ").append(n.name)
            append(", ").append(n.unit)
            append("; норма в сутки ").append(amount(n.norm)).append(' ').append(n.unit)
            append('\n')
        }
    }
