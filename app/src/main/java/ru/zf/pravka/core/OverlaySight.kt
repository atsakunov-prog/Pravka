package ru.zf.pravka.core

import kotlin.math.abs

/**
 * Видит ли система наши окна на самом деле — и что делать, если нет.
 *
 * Владелец (28.09.2026, Android 17 на Fold): «когда телефон складывается,
 * диск с кнопками пропадает… и помогает только перезапустить службу».
 * Журнал при этом честно говорил обратное: «кнопок на экране 4 из 5, стекло
 * висит», экран 2076x2152, координаты в экране. То есть окна повешены, на
 * своих местах, `addView` прошёл, `isAttachedToWindow` — да, а на экране их
 * нет. Перевешивание при раскладывании (тот же `configSettled`) не помогало,
 * перезапуск службы — помогал. Значит, сломано не окно, а то, что у всех
 * наших окон общее и что живёт ровно столько, сколько подключение службы:
 * так бывает, когда система на время перехода складывания прячет оверлеи
 * службы общим слоем (`AsyncRotationController` гасит «токен» окон в ноль и
 * проявляет его, когда окна перерисуются в новом экране) и не проявляет
 * обратно. Свои флаги этого не видят в принципе — видит только система.
 *
 * Поэтому правда берётся у неё: список окон доступности (`getWindows()`)
 * строится из того, что реально показано на экране, — окна под погашенным
 * слоем или ни разу не нарисованные в него не попадают. Наше окно узнаётся по
 * размеру: кнопка — квадрат своего размера, стекло — свой квадрат (обрезанный
 * краем экрана). Размер, а не место: диск в эти секунды может ехать к краю,
 * а список окон у системы запаздывает на кадр-другой — по месту выходило бы
 * «не вижу» ровно тогда, когда всё видно.
 */
object OverlaySight {

    /** Окно на экране: левый верхний угол включительно, правый нижний — нет. */
    data class Box(val left: Int, val top: Int, val right: Int, val bottom: Int) {
        val width: Int get() = right - left
        val height: Int get() = bottom - top
        val empty: Boolean get() = width <= 0 || height <= 0

        /** Часть окна в пределах экрана [w]×[h] — список окон системы обрезан экраном так же. */
        fun clip(w: Int, h: Int): Box =
            Box(left.coerceIn(0, w), top.coerceIn(0, h), right.coerceIn(0, w), bottom.coerceIn(0, h))
    }

    /** Итог одного взгляда: сколько наших окон должно быть видно, сколько видно, сколько окон назвала система вообще. */
    data class Look(val expected: Int, val seen: Int, val listed: Int)

    /** Сколько наших окон на экране вообще должно быть видно: целиком за краем — не в счёт. */
    fun expected(ours: List<Box>, w: Int, h: Int): Int = ours.count { !it.clip(w, h).empty }

    /**
     * Сколько наших окон ([ours], по нашим параметрам) нашлось среди
     * оверлеев, которые система показывает ([overlays], её границы). Пара —
     * по размеру с допуском [slack]; из подходящих по размеру берётся
     * ближайший по месту, и каждое окно системы засчитывается одному нашему:
     * пять кнопок одного размера не должны «найтись» в одной.
     */
    fun seen(ours: List<Box>, overlays: List<Box>, w: Int, h: Int, slack: Int): Int {
        val free = overlays.filterNot { it.empty }.toMutableList()
        var found = 0
        for (o in ours.map { it.clip(w, h) }.filterNot { it.empty }) {
            val match = free
                .filter { abs(it.width - o.width) <= slack && abs(it.height - o.height) <= slack }
                .minByOrNull { abs(it.left - o.left) + abs(it.top - o.top) }
                ?: continue
            free.remove(match)
            found++
        }
        return found
    }

    enum class Step {
        /** Видно (хотя бы одно окно) или показывать нечего. */
        FINE,

        /** Система не назвала ни одного окна — взгляд не состоялся, судить не о чем. */
        UNKNOWN,

        /** Не видно — снять и повесить окна заново, потом посмотреть ещё раз. */
        REHANG,

        /** Не видно и после перевешивания, но сейчас идёт работа — перезапуск подождёт. */
        LATER,

        /**
         * Не видно и после перевешивания — посмотреть ещё раз, прежде чем
         * перезапускать: переход складывания мог ещё идти, а на время перехода
         * система гасит наши окна законно. Перезапуск — только по двум «не
         * вижу» подряд после перевешивания.
         */
        CONFIRM,

        /** Не видно и после перевешивания — перезапустить службу, как это делал владелец руками. */
        RESTART,

        /** Не видно, а перезапускать нельзя (проверке не доверяем или перезапуск только что был) — сказать словами. */
        GIVE_UP,

        /**
         * Проверка слепа: на чистом старте, когда окна заведомо на экране, она
         * их не нашла. Тогда её «не вижу» ничего не значит — ни перевешивать,
         * ни перезапускать, ни будить владельца; только строка в журнал.
         */
        BLIND,
    }

    /** Перезапуск службы — не чаще раза в полчаса: не помог — дальше решает владелец, а не петля. */
    const val RESTART_GAP_MS = 30 * 60_000L

    /** Сколько раз «подождать» работу, прежде чем сдаться: 20 × 30 с — десять минут. */
    const val MAX_LATER = 20

    /**
     * Что делать после взгляда [look].
     *
     * [cleanStart] — взгляд на старте службы, а окна вешались при открытом
     * телефоне и складываний с тех пор не было: они заведомо видны, и «не
     * вижу» здесь — слепота самой проверки; [blind] — это уже выяснилось
     * раньше в эту жизнь службы.
     * [rehung] — окна уже перевешивали после прошлого «не вижу»; [trusted] —
     * этот же взгляд в эту жизнь службы уже видел наши окна (иначе «не вижу»
     * может быть и слепотой самой проверки — тогда только перевешивание и
     * слова, без перезапуска); [idle] — ни записи, ни запроса к Claude, ни
     * открытого приложения; [sinceRestartMs] — с прошлого самоперезапуска;
     * [laterTries] — сколько раз уже ждали работу; [confirmed] — «не вижу»
     * после перевешивания уже было и подтверждается этим взглядом.
     */
    fun next(
        look: Look,
        cleanStart: Boolean,
        blind: Boolean,
        rehung: Boolean,
        trusted: Boolean,
        idle: Boolean,
        sinceRestartMs: Long,
        laterTries: Int,
        confirmed: Boolean,
    ): Step = when {
        look.expected == 0 -> Step.FINE
        look.listed == 0 -> Step.UNKNOWN
        look.seen > 0 -> Step.FINE
        cleanStart || blind -> Step.BLIND
        !rehung -> Step.REHANG
        // Подтверждение — и перед словами владельцу: переход, который ещё
        // идёт, не повод ни для перезапуска, ни для уведомления.
        !confirmed -> Step.CONFIRM
        !trusted -> Step.GIVE_UP
        sinceRestartMs < RESTART_GAP_MS -> Step.GIVE_UP
        !idle -> if (laterTries < MAX_LATER) Step.LATER else Step.GIVE_UP
        else -> Step.RESTART
    }
}
