package ru.zf.pravka.core

import kotlin.math.abs
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.hypot
import kotlin.math.roundToInt
import kotlin.math.sin
import kotlin.math.sqrt
import kotlin.math.tan

/**
 * Геометрия диска плавающих кнопок: шестерёнка в центре, кнопки по кольцу
 * вокруг неё, под ними стекло-тарелка. Владелец (19.09.2026): «крутящийся
 * диск, который наполовину виден из края экрана; четыре кнопки и посередине
 * кнопка настроек; если нажимаю на неё долго, за неё двигаю диск; у края он
 * виден только наполовину, и я могу его крутить».
 *
 * Углы — в градусах, по часовой, 0° — вправо: экранная ось y смотрит вниз,
 * так что «по часовой» здесь совпадает с ростом угла. Единицы — пиксели.
 * Без Android-зависимостей: JVM-тесты гоняют ту же арифметику, что и
 * `trigger/DiskController.kt`.
 *
 * Дом диска — поворот 0: первые две кнопки («П» и «З», ими пользуются чаще
 * всего) стоят по бокам от «лица» — направления внутрь экрана, «П» сверху,
 * «З» снизу. Докованный к правому краю диск смотрит влево: «П» вверху-слева,
 * «З» внизу-слева, «Д» и инструменты за краем. Так половина, которая видна,
 * всегда та, что нужна.
 */
object DiskGeometry {

    /**
     * Радиус кольца, на котором стоят центры кнопок: половина шестерёнки,
     * полтора просвета, половина кнопки. Полтора, а не один: от шестерёнки до
     * кнопок пальцу нужен зазор — тап по краю кнопки не должен задевать её.
     */
    fun ringRadius(buttonSize: Int, gearSize: Int, gap: Int): Float =
        gearSize / 2f + gap * 1.5f + buttonSize / 2f

    /** Радиус тарелки: до внешнего края кнопок плюс три четверти просвета полей. */
    fun plateRadius(buttonSize: Int, gearSize: Int, gap: Int): Float =
        ringRadius(buttonSize, gearSize, gap) + buttonSize / 2f + gap * 0.75f

    /**
     * На сколько центр докованного диска отступает от края экрана: ни на
     * сколько — центр ровно на краю, шестерёнка видна наполовину. Владелец
     * (19.09.2026, вечер): «сам круг должен заходить больше за край: до
     * середины кружка настроек». Первая версия отступала на полшестерёнки и
     * полпросвета, чтобы шестерёнка была целиком, — оказалось, диск торчит.
     * Точка «всё убрано» при этом остаётся на экране целиком (её прижимает
     * сама голова): по ней жмут, чтобы вернуть всё.
     */
    const val DOCK_INSET = 0

    /**
     * Шаг между соседними кнопками и щелчок поворота: четыре — 90°, три —
     * 120°. Две — тоже 90°, а не 180°: пара рядом, как у четырёх, иначе
     * докованный диск показывал бы обе кнопки разрезанными краем.
     */
    fun spread(count: Int): Float = if (count <= 2) 90f else 360f / count

    /**
     * Какая доля радиуса тарелки остаётся на экране у УБРАННОГО диска —
     * краешек со стрелкой между «П» и «З». Владелец (22.09.2026): «когда они
     * убираются, они должны выдавливаться из диска наружу так, чтобы кнопки
     * были целиком видны… и между ними был бы краешек диска со стрелкой».
     * Четверть — не на глаз: стрелка сидит на кромке и уходит внутрь на
     * `ARROW_INSET` плюс свой размер (вместе — около 0,12 радиуса), так что
     * четверти хватает ей целиком и остаётся, куда попасть пальцем.
     */
    const val SLIVER = 0.25f

    /**
     * Насколько центр тарелки уходит ЗА край экрана у убранного диска: весь
     * радиус минус краешек. Дальше это число идёт в [dock] отрицательным
     * отступом.
     */
    fun tuckDepth(plateRadius: Float): Int = (plateRadius * (1f - SLIVER)).roundToInt()

    /**
     * Насколько передние кнопки («П» и «З») выступают от центра диска В
     * СТОРОНУ ЭКРАНА: они стоят по полшага от лица, и вдоль лица достаётся
     * только косинус этого полшага. Одна кнопка стоит прямо на лице — весь
     * радиус кольца.
     */
    fun frontReach(ringRadius: Float, count: Int): Float {
        if (count <= 1) return ringRadius
        return ringRadius * cos(Math.toRadians((spread(count) / 2f).toDouble())).toFloat()
    }

    /**
     * Насколько кнопки выдавлены из стекла у убранного диска: стекло уходит
     * за край ([tuckDepth]), а кнопки остаются на экране ЦЕЛИКОМ — дальняя
     * кромка передней кнопки встаёт в [edge] от края экрана. Считается вдоль
     * лица, то есть поперёк края; вертикаль кнопок не трогаем — между ними
     * ровно там и видно краешек.
     *
     * Ноль снизу: если кольцо и без того выносит кнопки на экран, вдавливать
     * их обратно к краю незачем.
     */
    fun extrusion(plateRadius: Float, ringRadius: Float, buttonSize: Int, count: Int, edge: Int): Float =
        (tuckDepth(plateRadius) + buttonSize / 2f + edge - frontReach(ringRadius, count)).coerceAtLeast(0f)

    /** Сколько лучей у контура стекла: два градуса на луч — глазу хватает с запасом. */
    const val BLOB_RAYS = 180

    /**
     * Сколько раз пройтись сглаживанием по кольцу лучей. Шесть проходов
     * трёхточечным окном — это разброс около четырёх градусов: ступенька,
     * с которой начинается кнопка, размазывается в плечо градусов на
     * восемь, а макушка над самой кнопкой оседает меньше чем на пиксель.
     */
    const val BLOB_SMOOTH = 6

    /**
     * Радиус «кармана» стекла под кнопкой: полкнопки плюс те же поля, что
     * тарелка даёт кнопке у своей кромки. Отсюда главное свойство: у
     * невыдавленного диска карман касается кромки изнутри
     * (`ringRadius + podRadius == plateRadius`), то есть контур остаётся
     * ровным кругом — растягивать нечего.
     */
    fun podRadius(buttonSize: Int, gap: Int): Float = buttonSize / 2f + gap * 0.75f

    /**
     * Контур стекла: круг тарелки, РАСТЯНУТЫЙ под каждую выдавленную кнопку.
     * Владелец (22.09.2026): «надо сделать так, чтобы кнопки растягивали диск
     * под собой. А то сейчас они выезжают. Надо чтобы они выдавливались
     * вместе с краем!»
     *
     * Считается лучами из центра тарелки: по каждому лучу берём самое дальнее
     * из того, что на нём есть, — кромка тарелки или дальний край кармана
     * кнопки. Так контур получается заведомо цельным и без самопересечений,
     * какими бы ни были размеры и поворот; объединять окружности честной
     * геометрией пришлось бы с разбором вырожденных случаев, а ошибка там
     * стоит дырки в стекле.
     *
     * Сырой максимум даёт обрыв там, где луч перестаёт задевать карман, —
     * это читалось бы как приклеенный шарик. Поэтому кольцо лучей
     * СГЛАЖИВАЕТСЯ: обрыв превращается в плечо, и стекло тянется за кнопкой,
     * как резина. Макушка при этом почти не оседает — над кнопкой профиль
     * пологий.
     *
     * [pods] — центры карманов парами (x, y) от центра тарелки. Возвращает
     * true, если стекло и правда растянуто: иначе контур — ровный круг, и
     * звать его лучами незачем. Буферы [out] и [tmp] — снаружи: контур
     * считается кадр в кадр, и мусорить массивами тут нельзя.
     */
    fun blob(out: FloatArray, tmp: FloatArray, plateRadius: Float, pods: FloatArray, podRadius: Float): Boolean {
        val n = out.size
        for (i in 0 until n) out[i] = plateRadius
        var stretched = false
        var p = 0
        while (p + 1 < pods.size) {
            val px = pods[p]
            val py = pods[p + 1]
            p += 2
            val d = hypot(px, py)
            // Карман целиком под тарелкой — тянуть нечего.
            if (d + podRadius <= plateRadius + 0.5f) continue
            stretched = true
            val phi = atan2(py, px)
            for (i in 0 until n) {
                val a = i * 2.0 * Math.PI / n - phi
                val across = d * sin(a)
                val k = podRadius * podRadius - across * across
                if (k <= 0.0) continue
                val far = (d * cos(a) + sqrt(k)).toFloat()
                if (far > out[i]) out[i] = far
            }
        }
        if (!stretched) return false
        repeat(BLOB_SMOOTH) { smoothRing(out, tmp) }
        return true
    }

    /** Один проход сглаживания по кольцу: среднее с соседями, через ноль. */
    private fun smoothRing(r: FloatArray, tmp: FloatArray) {
        val n = r.size
        for (i in 0 until n) {
            val prev = r[if (i == 0) n - 1 else i - 1]
            val next = r[if (i == n - 1) 0 else i + 1]
            tmp[i] = (prev + r[i] + next) / 3f
        }
        tmp.copyInto(r, 0, 0, n)
    }

    /**
     * Куда смотрит диск — внутрь экрана: в левой половине вправо (0°), в
     * правой влево (180°). Только по горизонтали: докуется диск к боковым
     * краям, под большой палец.
     */
    fun facing(cx: Float, frameW: Int): Float = if (cx < frameW / 2f) 0f else 180f

    /**
     * В какую сторону идёт раскладка по кольцу: от «П» к «З» — ВНИЗ по
     * внутренней стороне (владелец: «правка должна быть сверху полукруга, а
     * засечка внизу, я так привык»). У правого края (лицо влево) вниз по
     * внутренней стороне — это против часовой (углы убывают), у левого — по
     * часовой. Экранная ось y смотрит вниз, отсюда и знак: первая версия
     * шла по часовой с обеих сторон, и у правого края «П» оказалась внизу.
     * Раскладки двух краёв зеркальны — при переезде на другую половину экрана
     * диск перестраивается (см. `DiskController.slide`).
     */
    fun sense(facing: Float): Float = if (facing < 90f || facing > 270f) 1f else -1f

    /**
     * Угол кнопки в слоте [index] из [count] при повороте [rotation] и лице
     * [facing]: дома первая стоит на полшага ВВЕРХ от лица, дальше вниз по
     * внутренней стороне через шаг ([sense]). Одна кнопка — прямо на лице.
     */
    fun slotAngle(index: Int, count: Int, facing: Float, rotation: Float): Float {
        if (count <= 1) return norm(facing + rotation)
        val step = spread(count)
        val s = sense(facing)
        return norm(facing - s * step / 2f + s * index * step + rotation)
    }

    /** Левый верхний угол окна кнопки размером [size] на кольце радиуса [radius] под углом [angle]. */
    fun slotOrigin(cx: Float, cy: Float, radius: Float, angle: Float, size: Int): Pair<Int, Int> {
        val a = Math.toRadians(angle.toDouble())
        val x = cx + radius * cos(a).toFloat() - size / 2f
        val y = cy + radius * sin(a).toFloat() - size / 2f
        return x.roundToInt() to y.roundToInt()
    }

    /** Угол точки ([x], [y]) относительно центра, в [0, 360). */
    fun angleOf(cx: Float, cy: Float, x: Float, y: Float): Float =
        norm(Math.toDegrees(atan2((y - cy).toDouble(), (x - cx).toDouble())).toFloat())

    /** Что делает палец, поведший кнопку на диске. */
    enum class Pull {
        /** Крутит диск — как было. */
        TURN,
        /** Везёт диск вдоль края: докованный остаётся у края, убранный — убранным. */
        EDGE,
        /** Везёт диск целиком: тот отцепляется от края и едет за пальцем. */
        CARRY,
    }

    /**
     * Конус «вертикально»: палец отклонился от отвеса не больше чем на
     * столько градусов. Диагональ (45°) — уже «везу целиком», как и просили;
     * тридцать пять оставляют запас на дугу большого пальца у края.
     */
    const val UPRIGHT_DEG = 35f

    /**
     * Кнопка ближе этого к высоте центра кольца (доля радиуса) — ни верхняя,
     * ни нижняя: вертикальный ход у неё идёт ПО кольцу, то есть это поворот.
     */
    const val LEVEL = 0.3f

    /**
     * Что значит ход пальца по кнопке. Владелец (22.09.2026): «когда я тащу
     * вниз, то я тащу вертикально от нижней кнопки. Когда тащу наверх — то
     * вертикально от верхней кнопки. В этом случае надо сделать только ездить
     * по краю. Когда я беру какую-то кнопку и тащу горизонтально или по
     * диагонали, значит, я хочу перетащить целиком диск».
     *
     * Отсюда три исхода по первым миллиметрам хода ([dx], [dy]):
     * горизонталь и диагональ — [Pull.CARRY]; вертикаль ПРОЧЬ от центра
     * (верхняя кнопка вверх, нижняя вниз; [buttonDy] — кнопка от центра
     * кольца по высоте) — [Pull.EDGE]; вертикаль К центру (от верхней вниз,
     * к нижней) — [Pull.TURN], это прежнее смахивание, которым диск крутят.
     * Решается один раз на касание: иначе поворот, чуть вильнувший вбок,
     * посреди жеста отрывал бы диск.
     */
    fun pull(dx: Float, dy: Float, buttonDy: Float, ringRadius: Float): Pull {
        val upright = abs(dx) <= abs(dy) * tan(Math.toRadians(UPRIGHT_DEG.toDouble())).toFloat()
        if (!upright) return Pull.CARRY
        if (abs(buttonDy) < ringRadius * LEVEL) return Pull.TURN
        return if ((dy < 0f) == (buttonDy < 0f)) Pull.EDGE else Pull.TURN
    }

    /** Кратчайший поворот от [from] к [to], в (−180, 180]. */
    fun delta(from: Float, to: Float): Float {
        var d = (to - from) % 360f
        if (d <= -180f) d += 360f
        if (d > 180f) d -= 360f
        return d
    }

    /**
     * Инерция при переезде: диск катится. Везёшь его на [dx] пикселей вбок —
     * кольцо проворачивается, как колесо по поверхности: угол = путь делить
     * на радиус, со знаком «против направления». [k] — насколько охотно
     * (1,0 — настоящее качение без проскальзывания; владелец крутит его
     * ползунком, заводское меньше единицы: диск всё-таки не колесо, и полное
     * качение на широком экране уводило бы кнопки слишком далеко).
     *
     * Только вбок: вертикальное движение для катящегося диска — это подъём, а
     * не качение, и крутить от него значило бы врать глазу.
     */
    fun roll(dx: Float, plateRadius: Float, k: Float): Float {
        if (plateRadius <= 0f) return 0f
        return -Math.toDegrees((dx * k / plateRadius).toDouble()).toFloat()
    }

    /** Угол в [0, 360). */
    fun norm(angle: Float): Float {
        var a = angle % 360f
        if (a < 0f) a += 360f
        return a
    }

    /**
     * Ближайший щелчок поворота с учётом броска: палец отпустил диск со
     * скоростью [velocity] градусов в секунду — диск считает, куда долетит за
     * [FLICK_LEAD] секунды, и щёлкает там. Лёгкий бросок — соседний щелчок,
     * сильный — через один; ещё сильнее не бывает ([MAX_FLICK]): диск не
     * рулетка.
     */
    fun snap(rotation: Float, step: Float, velocity: Float = 0f): Float {
        val projected = rotation + velocity.coerceIn(-MAX_FLICK, MAX_FLICK) * FLICK_LEAD
        return (projected / step).roundToInt() * step
    }

    /** Ближайший «дом» — поворот, кратный 360°: возвращаться коротким путём, а не через весь круг. */
    fun home(rotation: Float): Float = (rotation / 360f).roundToInt() * 360f

    /**
     * Докование после броска. Тарелка радиуса [plateRadius] зашла за левый
     * или правый край рабочей области [frameW]×[frameH] — центр прижимается
     * к этому краю на [inset]; иначе остаётся где отпустили. По вертикали
     * тарелка всегда целиком на экране (или по центру, если экран ниже
     * тарелки).
     */
    fun dock(cx: Float, cy: Float, frameW: Int, frameH: Int, plateRadius: Float, inset: Int): Pair<Float, Float> {
        val x = when {
            cx - plateRadius < 0f -> inset.toFloat()
            cx + plateRadius > frameW -> (frameW - inset).toFloat()
            else -> cx
        }
        val minY = minOf(plateRadius, frameH / 2f)
        val maxY = maxOf(frameH - plateRadius, frameH / 2f)
        return x to cy.coerceIn(minY, maxY)
    }

    /**
     * Виден ли хоть кусок окна ([x], [y], [size]) в рабочей области с запасом
     * [margin]: окно целиком за краем снимается из WindowManager — складывание
     * Fold платит за каждое окно, видимое или нет.
     */
    fun onScreen(x: Int, y: Int, size: Int, frameW: Int, frameH: Int, margin: Int): Boolean =
        x + size > margin && x < frameW - margin && y + size > margin && y < frameH - margin

    /** Сколько секунд полёта учитывает бросок. */
    const val FLICK_LEAD = 0.15f
    /** Потолок скорости броска, градусов в секунду: с [FLICK_LEAD] это полкруга, два щелчка за мах — предел. */
    const val MAX_FLICK = 1200f
}
