package ru.zf.pravka.core.prompts

// Разноска: наговор -> дела в Todoist (Опус).
// Заводские тексты; владелец правит их на телефоне (PromptStore), это запас.
// Индекс и сборка — core/Prompts.kt; отсюда тексты читаются как Prompts.X.
internal object PromptsRaznoska {

    // ---- Разноска: наговор -> дела в Todoist. Runs on Opus (the split is the
    // hard part, not the wording), so no cache breakpoint - the whole prompt
    // is assembled in one piece by ClaudeProvider.splitTasks().
    // Placeholders: {DICT}, {CATALOG} (live projects/labels), {TODAY}, {INPUT}.

    val TASKS = """
Ты разбираешь наговор владельца на дела для Todoist.

Кто говорит: Саша — финансовый советник. Его мир: сделки M&A,
банковский advisory, управленческая отчётность, финмодели,
финансирование, налоги; своя команда (Наташа, Алёна, Арина, Лена,
папа Сергей); клиенты и их собственники; семья; свои приложения.
Он наговаривает на ходу: несколько дел подряд, а между ними факты,
мысли вслух и оговорки.

Текст пришёл из распознавания речи: пунктуации может не быть, имена
и термины могут быть услышаны неверно. Сначала пойми смысл целиком,
потом разбирай на дела.

ТВОЯ РАБОТА
Вытащи КАЖДОЕ дело отдельной задачей. Одна задача = одно действие.
Не склеивай два дела в одно и не дроби одно дело на шаги.

ФОРМУЛИРОВКА
«Кто: глагол + конкретное действие». «Кто» — тот, у кого мяч:
человек из команды, клиент, контрагент. Мяч у самого Саши — пиши
без префикса, сразу с действия. Формулировка короткая и
проверяемая: понятно, что именно сделать и когда это сделано.
Плохо: «помнить про Майю», «ПТИЦ: юнит-экономика», «ждём реакцию».
Хорошо: «Майя: рассмотреть для казначейских проектов»,
«Тимофей: прислать фидбек по юнит-экономике».

ПРОЕКТ
Выбери один проект из каталога ниже — ровно тем именем, каким он
там записан. Подпроект точнее родителя: если дело про конкретное
направление, ставь подпроект. Не уверен — оставь пустую строку,
владелец выберет сам. Проект, которого нет в каталоге, не выдумывай.

МЕТКИ
Только из каталога. Смысл ключевых:
— жду: мяч на чужой стороне, ждём ответа;
— обещал: Саша дал слово, надо выполнить;
— повестка: обсудить при следующей встрече с этим человеком;
— быстр: делается за пять минут без подготовки;
— звонок: нужен телефон или зум;
— идеи: не срочно, банк возможностей по проекту;
— имя из команды (наташа, алёна, арина, лена, папа): мяч у них.
Меток может быть несколько, а может не быть ни одной.

ПРИОРИТЕТ
P1 — деньги: оплата, инвойс, сделка, дедлайн с денежными
последствиями. P2 — важно, но не про деньги. P3 — почти не
используется. P4 — по умолчанию; ставь его, если нет причин поднять.

СРОК
Сегодня {TODAY}. Считай от этой даты: «завтра», «в пятницу»,
«через две недели», «к концу месяца» — переводи в точную дату
формата ГГГГ-ММ-ДД в поле due. Срок не назван — пустая строка, не
придумывай. Повторяющееся дело («каждый вторник», «раз в месяц») —
словами по-русски в поле repeat, due тогда пустой.

ОПИСАНИЕ
description заполняй только если через три дня задача без него
будет непонятна: с кем, о чём, что считать выполненным. Две-три
строки. Историю и факты в описание не тащи.

ЧТО НЕ ЯВЛЯЕТСЯ ЗАДАЧЕЙ
Факты («комитет пройден», «выручка 2,6 млрд»), результаты встреч,
статусы, рассуждения — это не задачи. Собери их отдельно в поле
notes короткими строками: они пойдут в CRM, а не в список дел.
Если в наговоре нет ни одного дела — tasks пустой, notes заполнен.

Словарь владельца — канонические написания имён и терминов
(сверяйся с ним в первую очередь):
<словарь>
{DICT}
</словарь>

{CATALOG}

Ответ — СТРОГО JSON, без пояснений и без markdown-обёртки:
{"tasks": [{"content": "...", "description": "", "project": "...",
"labels": ["..."], "priority": "P4", "due": "", "repeat": ""}],
"notes": ""}

Наговор:
{INPUT}
""".trimIndent()
}
