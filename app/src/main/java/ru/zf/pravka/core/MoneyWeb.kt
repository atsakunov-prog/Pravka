package ru.zf.pravka.core

/**
 * Разделы веба «Деньги», которых нет на телефоне (Правка 5.0, доводка 14.10.2026;
 * холст `Dengi.dc.html`: «Бюджет», «P&L», «Доля», «Чего не видим»). Их считает
 * сервис «Деньги» на компе из журнала архива — у телефона нет ни бюджета статьями,
 * ни правил партнёрства, ни сторожа дыр, и переписывать их сюда значило бы
 * завести вторую правду. Поэтому на вкладке «Траты» — строки-входы: раздел
 * открывается страницей сервиса внутри приложения (`ServicePage`, тот же путь,
 * что у меню Ковчега).
 *
 * Адрес сервиса — только из синка (`look.nav` → `DelaSync.services`, ключ
 * `dengi`): адресов в коде нет, репозиторий публичный. Раздел — фрагментом
 * `#<вкладка>` (имена вкладок веба: `data-tab` в `index.html` сервиса): так
 * адрес у каждого раздела свой, а сервер его не видит вовсе.
 */
object MoneyWeb {

    /** Раздел веба: [tab] — имя вкладки веба, подпись, мелкая подпись и значок набора Ковчега. */
    data class Section(val tab: String, val title: String, val sub: String, val icon: String)

    /** Ключ сервиса «Деньги» в меню Свода и `look.nav`. */
    const val KEY = "dengi"

    val SECTIONS: List<Section> = listOf(
        Section("pnl", "P&L и бюджет", "факт по месяцам, вперёд — бюджет или прогноз", "chart"),
        Section("articles", "Статьи", "что входит в каждую строку P&L", "list"),
        Section("rules", "Доля партнёра", "партнёрство в ЗФ и долг по доле", "briefcase"),
        Section("gaps", "Чего не видим", "сторож дыр: где журнал неполон", "alert"),
    )

    /** Адрес сервиса «Деньги» из синка ([nav], относительный — от адреса Дел [base]); нет его — null. */
    fun service(nav: List<Kovcheg.Nav>, base: String?): String? =
        nav.firstOrNull { it.key == KEY }?.let { Kovcheg.absolute(it.url, base) }

    /** Адрес раздела: адрес сервиса без своего фрагмента и `#<вкладка>`. */
    fun url(service: String, tab: String): String = service.substringBefore('#') + "#" + tab
}
