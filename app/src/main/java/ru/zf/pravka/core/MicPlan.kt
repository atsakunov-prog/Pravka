package ru.zf.pravka.core

/**
 * Куда смотреть микрофону в этом тейке — решение без Android под рукой.
 *
 * Правило проекта: микрофон выбирает владелец, а не подключение
 * (`docs/agreements.md`). Само по себе оно простое, а вот что с ним делать —
 * зависит от того, занят ли сейчас канал связи чужим: в машине телефон сам
 * уезжает в хендс-фри, и системный распознаватель слушает салонный микрофон
 * у лобового, а не тот, что в руке. Отсюда три исхода, и каждый стоит своих
 * миллисекунд: маршрут переезжает не мгновенно, и стартовать распознаватель
 * раньше переезда — значит отдать первые слова прежнему входу.
 *
 * Логика вынесена сюда, потому что `AudioManager` на JVM не заводится, а
 * ошибиться здесь легко: до 22.09.2026 «телефон» ронял чужой канал вслепую и
 * шёл слушать, не дожидаясь, пока система переложит вход.
 */
object MicPlan {

    enum class Route {
        /** Ничего не трогаем — система и так слушает то, что надо. Самый быстрый старт. */
        AS_IS,

        /**
         * Прибить связь к телефону: канал гарнитуры поднят (машина, чужое
         * приложение), а слушать владелец велел телефон. Просто «опустить
         * чужой канал» нельзя — он не наш; поэтому мы просим СВОЁ устройство
         * связи, встроенное, и последнее слово остаётся за нами.
         */
        BUILTIN,

        /** Поднять канал гарнитуры и дождаться его: гарнитуру выбрали и она на месте. */
        HEADSET,
    }

    /**
     * @param phoneMic владелец выбрал микрофон телефона (иначе — гарнитуру)
     * @param headsetPresent гарнитура видна среди входов
     * @param btRouteUp канал связи сейчас поднят (кем угодно)
     * @param callInProgress идёт разговор — в маршрут не лезем вообще
     */
    fun choose(
        phoneMic: Boolean,
        headsetPresent: Boolean,
        btRouteUp: Boolean,
        callInProgress: Boolean,
    ): Route = when {
        // Разговор важнее диктовки: перекладывать маршрут посреди звонка —
        // это оборвать звук собеседнику. Слушаем, как есть.
        callInProgress -> Route.AS_IS
        !phoneMic && headsetPresent -> Route.HEADSET
        // Гарнитуру выбрали, а её нет: слушаем телефон и не трогаем ничего.
        !phoneMic -> Route.AS_IS
        // Телефон выбран, а канал занят машиной или наушниками — забираем вход себе.
        btRouteUp -> Route.BUILTIN
        else -> Route.AS_IS
    }

    /**
     * Ждать ли переезда маршрута перед стартом распознавателя. Ждём только
     * тогда, когда сами что-то переложили: [changed] — система приняла
     * заявку. Не приняла (нет прав, нет устройства) — ждать нечего, старт
     * без задержки честнее лишних полутора секунд тишины.
     */
    fun waitsForRoute(route: Route, changed: Boolean): Boolean =
        changed && route != Route.AS_IS

    // ---- Смена микрофона посреди тейка ----
    //
    // Кружок в пилюле рядом с «отправить» (владелец, 28.09.2026: «регулярно я
    // нажимаю на телефоне, а потом хочу просто на наушниках продолжить всё
    // говорить и ходить по квартире»). Начал у телефона, надел наушники и
    // ушёл — а слушает по-прежнему телефон на столе, и слова пропадают.
    // Тейк при этом не останавливается: Android сам переводит идущую запись
    // на новый вход, когда меняется устройство связи; что она переехала,
    // сверяется по записи распознавателя у системы (`MicRouting.recognizerInput`).

    enum class Change {
        /** Перевести связь на гарнитуру (поднять её канал). */
        HEADSET,

        /** Забрать вход телефону: связь смотрит на гарнитуру — свою или чужую. */
        BUILTIN,

        /** Уже слушает то, что просят, — трогать нечего. */
        NOTHING,

        /** Идёт разговор — маршрут не трогаем, как и на старте. */
        CALL,

        /** Гарнитуры среди входов нет — остаётся телефон. */
        NO_HEADSET,
    }

    /**
     * @param wantHeadset на что переключают
     * @param headsetPresent гарнитура видна среди входов
     * @param headsetRouted устройство связи — именно гарнитура (не «канал
     *   поднят кем-то»: машина могла держать канал, а мы — забрать вход
     *   телефону, и тогда слушает телефон)
     * @param btRouteUp канал гарнитуры поднят кем угодно
     * @param callInProgress идёт разговор
     */
    fun change(
        wantHeadset: Boolean,
        headsetPresent: Boolean,
        headsetRouted: Boolean,
        btRouteUp: Boolean,
        callInProgress: Boolean,
    ): Change = when {
        callInProgress -> Change.CALL
        wantHeadset && !headsetPresent -> Change.NO_HEADSET
        wantHeadset -> if (headsetRouted) Change.NOTHING else Change.HEADSET
        headsetRouted || btRouteUp -> Change.BUILTIN
        else -> Change.NOTHING
    }

    /**
     * Что показывает кружок микрофона в пилюле: кто слушает этот тейк и
     * слышит ли прямо сейчас. [hearing] ложно, пока движок ещё не отозвался,
     * поднимается после ошибки или маршрут переезжает, — ровно те окна, где
     * сказанное пропадает (`core/TakeHealth.kt`).
     */
    data class Mic(val headset: Boolean, val hearing: Boolean)
}
