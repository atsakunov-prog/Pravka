package ru.zf.pravka.core

/**
 * Обратный отсчёт на занятой кнопке — вместо дуги прогресса по кромке диска.
 * Владелец (26.09.2026): «ползущий прогресс-бар плохо работает на свёрнутом
 * диске… давай сделаем упрощение: на самой кнопке, где просто крутится,
 * обратный отсчёт в виде секунд… 9, 8, 7, 6, и, может быть, секунды с
 * десятыми, чтобы было видно, как это идёт, и до нуля».
 *
 * Сколько ждать — всё та же оценка `Pace` по своей истории (дорога, модель,
 * усилие, длина входа): поменялся только способ показать. Дуга у убранного
 * диска шла по полукругу за краем и читалась плохо; число на кнопке видно
 * всегда, где бы кнопка ни стояла.
 *
 * Срок вышел, а ответа нет — [label] отдаёт null, и кнопка снова крутит
 * колесо: замершее «0,0» читалось бы как «повисло», а колесо честно говорит
 * «ещё работаю».
 */
object Countdown {

    /**
     * Что написать на кнопке, когда до обещанного осталось [remainingMs]. От
     * десяти секунд — целые («12»), меньше — с десятыми через запятую
     * («9,4»), до «0,0» в последние сто миллисекунд. Округляем вниз: число не
     * должно обещать больше, чем осталось.
     */
    fun label(remainingMs: Long): String? {
        if (remainingMs < 0L) return null
        if (remainingMs >= 10_000L) return (remainingMs / 1000L).toString()
        val tenths = remainingMs / 100L
        return "${tenths / 10},${tenths % 10}"
    }

    /**
     * Какие дороги считаются на кнопке: те, что запускает сама кнопка
     * (`data/ModelRoutes.kt`). Разборы по ночам, вопросы из вкладок, сверка
     * — не её: их отсчёт лёг бы на занятую кнопку чужим числом.
     */
    fun onButton(route: String): Boolean = route in BUTTON_ROUTES

    private val BUTTON_ROUTES = setOf(
        "pravka", "pravka_strong",
        "zasechka", "zasechka_fork",
        "raznoska",
        "money",
        "food", "body",
    )
}
