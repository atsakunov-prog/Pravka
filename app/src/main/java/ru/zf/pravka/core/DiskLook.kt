package ru.zf.pravka.core

import kotlin.math.roundToInt

/**
 * Вид диска плавающих кнопок: цвет стекла и плотности слоёв — арифметикой,
 * без Android. Рисует по этим числам `trigger/DiskController.PlateView`,
 * проверяет их JVM-тест.
 *
 * Владелец (19.09.2026, ночь): «диск сбоку хочется сделать стильным… давай
 * наоборот, светлее, чем бэкграунд. А то теряется иногда. И сделаем тумблер в
 * настройках: светлее/темнее». Отсюда две шкурки стекла — бумага и чернила —
 * и тумблер между ними (`Settings.diskLightFlow`, с завода светлая).
 *
 * Почему числа живут здесь, а не в самом виде: светлая шкурка — не просто
 * другой цвет. Бумаге на экране нужно стоять плотнее чернил (тонкая белая
 * вуаль читается хуже тонкой тёмной), а её край и тень — работать против
 * светлого фона, иначе диск пропадёт уже на белом, только с другой стороны.
 * Каждый коэффициент ниже — про это, и каждый под тестом.
 */
object DiskLook {

    /** Тёмное стекло — чернила: диск не спорит цветом с кнопками (было с 19.09). */
    val GLASS_DARK = 0xFF3A342B.toInt()

    /** Светлое стекло — тёплая бумага, та же, что на плашках вкладок. */
    val GLASS_LIGHT = 0xFFF7F3EA.toInt()

    fun glass(light: Boolean): Int = if (light) GLASS_LIGHT else GLASS_DARK

    /**
     * Плотность стекла от прозрачности кнопок: тарелка заметна, но стоит ПОД
     * кнопками и не спорит с ними. Бумаге дано больше чернил: белая вуаль
     * поверх пёстрого приложения теряется раньше тёмной.
     */
    fun plateAlpha(fabAlpha: Float, light: Boolean): Float =
        (fabAlpha * if (light) 0.62f else 0.45f).coerceIn(0f, 1f)

    /**
     * Центр стекла прозрачнее края: под диском остаётся видно приложение, а
     * край читается как толщина предмета, а не как обводка виджета.
     */
    fun centreAlpha(fill: Float): Float = fill * 0.55f

    /**
     * Тень под стеклом: вдвое плотнее самого стекла, с потолком. Диск —
     * предмет над приложением; светлой тарелке тень нужнее тёмной, и она же
     * её и получает — тень считается от плотности стекла, а та у бумаги выше.
     */
    fun shadowAlpha(fill: Float): Float = (fill * 2f).coerceAtMost(0.45f)

    /**
     * Блик по верхнему краю тарелки: свет сверху, кромка ловит его. У бумаги
     * ярче — на ней блик и читается как фаска, у чернил это была бы белая
     * линия по тёмному, то есть обводка.
     */
    fun rimLightAlpha(fill: Float, light: Boolean): Float =
        (fill * if (light) 2.4f else 1.5f).coerceAtMost(0.55f)

    /** Тёмная кромка снизу — вторая половина той же фаски. */
    fun rimShadeAlpha(fill: Float, light: Boolean): Float =
        (fill * if (light) 1.3f else 0.9f).coerceAtMost(0.32f)

    /**
     * Лицо кнопки на диске. Владелец, увидев светлое стекло (19.09, ночь):
     * «выглядит сейчас так, что диск над кнопками, а не наоборот. Давай
     * сделаем кнопки над диском (понасыщеннее цвет получается)».
     *
     * Кнопки и правда висели НАД стеклом — окнами. Но полупрозрачными, и
     * светлая тарелка просвечивала сквозь них: глаз читает светлое как
     * ближнее, и порядок слоёв переворачивался. Лечится не порядком окон, а
     * плотностью — на диске кнопка почти не просвечивает, а «не мешать
     * приложению» держит сама тарелка, она для того и полупрозрачная.
     * Слайдер прозрачности при этом жив: на диске он двигает лицо в верхней
     * трети (0,7…1), а не от нуля. В стопке всё как было — там кнопка висит
     * прямо на приложении, и её прозрачность действительно нужна.
     */
    fun faceAlpha(fabAlpha: Float, onDisk: Boolean): Float {
        val a = fabAlpha.coerceIn(0f, 1f)
        return if (onDisk) 0.7f + 0.3f * a else a
    }

    /**
     * Тень кнопки на тарелке — второй ответ на тот же вопрос «кто над кем».
     * Наружу кнопка тень отбросить не может (окно ровно по кружку), но
     * стекло под ней — может нарисовать её у себя. На бумаге тень работает,
     * на чернилах почти не видна, поэтому там она слабее: незачем платить
     * кадрами за то, чего не разглядеть.
     */
    fun socketAlpha(fill: Float, light: Boolean): Float =
        (fill * if (light) 1.2f else 0.8f).coerceAtMost(0.3f)

    /**
     * Чем рисовать шестерёнку посреди диска (владелец: «посередине
     * шестерёнку надо без бэкграунда»): без подложки она сама себе знак, и
     * цвет берёт у стекла — чернила на бумаге, бумага на чернилах.
     */
    fun gearInk(light: Boolean): Int = if (light) GLASS_DARK else GLASS_LIGHT

    /** Цвет с заданной прозрачностью (0..1); RGB не трогаем. */
    fun withAlpha(color: Int, alpha: Float): Int =
        ((alpha.coerceIn(0f, 1f) * 255).roundToInt() shl 24) or (color and 0x00FFFFFF)

    /** Белый заданной прозрачности — блик. */
    fun white(alpha: Float): Int = withAlpha(0x00FFFFFF, alpha)

    /** Чёрный заданной прозрачности — тень и кромка. */
    fun black(alpha: Float): Int = withAlpha(0x00000000, alpha)
}
