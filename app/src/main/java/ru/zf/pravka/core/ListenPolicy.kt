package ru.zf.pravka.core

/**
 * Когда тейк кончается сам, без кнопки, — решение без Android под рукой.
 *
 * Правило (владелец, 23.09.2026): «Правка прежде всего должна слушать то, что
 * я говорю. Если я замолк, то не надо убивать сессию». Тишина — не конец
 * тейка: человек читает, думает, отвечает кому-то в комнате. Раньше
 * непрерывная сессия распознавателя закрывалась после 30 секунд тишины
 * (`EXTRA_SPEECH_INPUT_COMPLETE_SILENCE_LENGTH_MILLIS` у segmented-режима —
 * это и есть её конец), а мы на `onEndOfSegmentedSession` честно отдавали
 * текст в чистку. В режиме перезапусков то же делала серия NO_MATCH /
 * SPEECH_TIMEOUT: сорок пауз подряд — и «микрофон мёртв».
 *
 * Теперь тейк кончает владелец. Единственная страховка — от случайного
 * нажатия: если [IDLE_CAP_MS] не пришло ни одного нового слова, запись
 * закрывается сама («чтобы не слушала там час, а минут через десять
 * замолкала»). Считается от последнего СЛОВА, а не от старта: длинная
 * диктовка с паузами не обрывается посреди мысли.
 */
object ListenPolicy {

    /** Десять минут без единого нового слова — нажали случайно. */
    const val IDLE_CAP_MS = 10L * 60 * 1000

    /** Как часто сторож тишины смотрит на часы: точность тут не нужна. */
    const val IDLE_CHECK_MS = 30_000L

    /** Короче этого сессия не «поработала», а сорвалась. */
    const val SESSION_MIN_MS = 2_000L

    /** Столько срывов подряд без единого слова — поднимать больше нечего. */
    const val MAX_QUICK_ENDS = 5

    /** Пауза перед подъёмом сессии: движку дают выдохнуть, и петля не горячая. */
    const val RESUME_DELAY_MS = 200L

    /**
     * Потолок записи «З», начатой пальцем с заблокированного экрана.
     * Владелец: «через 40 секунд вообще, потому что я больше и не говорю».
     * Разблокировал — потолок снимается: он тут и говорит сколько нужно.
     */
    const val LOCKED_TAKE_CAP_MS = 40_000L

    /**
     * Потолок записи с локскрина, мс; 0 — потолка нет. Тейк с кнопки
     * гарнитуры живёт как у Правки — до кнопки или [IDLE_CAP_MS] без слов
     * (владелец, 25.09.2026: «лимит тогда надо поставить как в правке»): с
     * развилкой в Засечку идут мысли и списки дел, им сорока секунд мало, а
     * от кармана защищать нечего — гарнитуру две секунды случайно не жмут.
     */
    fun lockedCapMs(fromHeadset: Boolean): Long = if (fromHeadset) 0L else LOCKED_TAKE_CAP_MS

    // Коды SpeechRecognizer: ERROR_SPEECH_TIMEOUT = 6, ERROR_NO_MATCH = 7.
    // Числа, а не константы Android, — чтобы решение жило под JVM-тестом.
    private const val SPEECH_TIMEOUT = 6
    private const val NO_MATCH = 7

    /**
     * Ошибка — это просто тишина (никто не говорил / сказанное не разобрали).
     * Такая ошибка не приближает «сдаться»: она не про сломанный микрофон.
     */
    fun isSilence(code: Int): Boolean = code == SPEECH_TIMEOUT || code == NO_MATCH

    /** Слов не было так долго, что запись пора закрыть самим. */
    fun idleExpired(lastWordsAtMs: Long, nowMs: Long): Boolean =
        nowMs - lastWordsAtMs >= IDLE_CAP_MS

    /**
     * Распознаватель закрыл сессию сам (тишина). Если владелец запись не
     * останавливал и страховка не сработала — слушаем дальше, а не отдаём
     * текст.
     */
    fun resumeAfterSessionEnd(active: Boolean, stopping: Boolean, lastWordsAtMs: Long, nowMs: Long): Boolean =
        active && !stopping && !idleExpired(lastWordsAtMs, nowMs)

    /**
     * Сессия, кончившаяся раньше собственной тишины, — это срыв, а не пауза
     * владельца (у движка отобрали микрофон, служба не в себе). Поднимать её
     * бесконечно значит устроить тот самый шторм, из-за которого в
     * `GoogleSpeechSession` нельзя пересоздавать распознаватель на ошибке.
     * Возвращает число срывов подряд: слово или нормально отработавшая сессия
     * обнуляют счёт.
     */
    fun countCollapse(previous: Int, ranMs: Long): Int =
        if (ranMs < SESSION_MIN_MS) previous + 1 else 0

    /** Срывов подряд столько, что поднимать больше нечего — отдаём, что есть. */
    fun giveUpOnCollapses(collapses: Int): Boolean = collapses >= MAX_QUICK_ENDS

    /**
     * Через сколько поднимать распознаватель после ошибки, мс; 0 — сразу,
     * следующим сообщением очереди.
     *
     * Каждая миллисекунда паузы здесь — время, когда тейк идёт, а слушать
     * некому (владелец, 28.09.2026: «много пропускает слов»). До этого пауза
     * была у ЛЮБОЙ ошибки: 600 мс с первой, до полутора секунд подряд, — и
     * тишина («не разобрал», «никто не говорил») платила её так же, как
     * мёртвая сеть. Тишина после сессии, которая честно поработала, — это
     * человек замолчал и сейчас продолжит: слушать надо сразу. Пауза остаётся
     * там, где она защищает: [hardErrors] настоящих ошибок подряд (сеть,
     * служба) и [quickSilences] «тишин», прилетевших быстрее
     * [SESSION_MIN_MS] после старта, — движок, отвечающий «не разобрал»
     * мгновенно, без паузы закрутился бы в горячую петлю.
     */
    fun restartDelayMs(hardErrors: Int, quickSilences: Int): Long {
        val n = hardErrors.coerceAtLeast(0) + quickSilences.coerceAtLeast(0)
        return if (n == 0) 0L else (RESTART_BASE_MS + n * RESTART_STEP_MS).coerceAtMost(RESTART_MAX_MS)
    }

    // ---- Застрял: слышит речь, а слов не отдаёт ----
    //
    // Владелец (28.09.2026): «когда очень долго что-то говорю, иногда в конце
    // может застревать и просто вообще уже ничего не воспринимать… что бы я
    // ни говорил, ничего не получается». В журнале это видно так: начало и
    // конец речи идут как часы, куски приходят один за другим — пустые.
    // Сессия жива для самой себя и мертва для владельца, и ни ошибки, ни
    // конца сессии нет, так что прежние сторожа её не видели.

    /** Столько речи подряд без единого слова — распознаватель застрял. */
    const val STUCK_SPEECH_MS = 6_000L

    /**
     * Кусок почти без слов: [chars] новых знаков за [speechMs] речи. Пустой —
     * без слов всегда; с парой слов на много секунд речи — тоже (владелец,
     * 30.09.2026: «где-то замолчал, и дальше плашки вообще не было никаких
     * слов»; в журнале — 13,5 с речи и 10 знаков, потом пустые куски). До
     * этого любое слово сбрасывало счёт, и оглохшая после паузы сессия
     * дотягивала так до конца тейка. Живая речь владельца — 6–11 знаков на
     * секунду речи, самый тощий здоровый кусок в журнале — 3; порог вдвое ниже.
     * Короткие куски не судим: «да» за секунду — это нормально.
     */
    fun fewWords(chars: Int, speechMs: Long): Boolean =
        chars <= 0 || (speechMs >= THIN_MIN_SPEECH_MS && chars < speechMs / 1000.0 * THIN_CHARS_PER_S)

    /** Меньше стольких знаков на секунду речи — кусок почти пуст. */
    const val THIN_CHARS_PER_S = 1.5

    /** Короче этой речи кусок по густоте не судим. */
    const val THIN_MIN_SPEECH_MS = 5_000L

    /** После стольких подъёмов подряд без слов — сказать владельцу словами. */
    const val STUCK_NOTICE_AFTER = 2

    /**
     * Больше стольких подъёмов подряд без слов — поднимать реже: это, скорее,
     * уже не распознаватель, а микрофон далеко или вокруг чужая речь, и
     * частая петля подъёмов только жгла бы батарею. Но и не бросать совсем:
     * по-настоящему застрявшая сессия иначе молчала бы до конца тейка.
     */
    const val STUCK_MAX_RESTARTS = 4

    /** После [STUCK_MAX_RESTARTS] подъёмов подряд — следующий только через столько речи без слов. */
    const val STUCK_LATE_MS = 30_000L

    /** Столько речи без слов накопилось — пора решать, поднимать ли заново. */
    fun stuck(mutedSpeechMs: Long): Boolean = mutedSpeechMs >= STUCK_SPEECH_MS

    /** Поднимать ли, если подряд уже [restarts] подъёмов без слов и речи без слов [mutedSpeechMs]. */
    fun mayRestartStuck(restarts: Int, mutedSpeechMs: Long): Boolean =
        restarts < STUCK_MAX_RESTARTS || mutedSpeechMs >= STUCK_LATE_MS

    /**
     * С какого мига повторить звук новой сессии (своя запись, `MicFeed`): с
     * последнего разобранного слова — всё, что прежняя сессия прочла и не
     * отдала, разбирается заново, — но не дальше [REPLAY_MAX_MS] назад:
     * минуты тишины перед ошибкой распознаватель жевал бы, пока владелец
     * ждёт живой строки.
     */
    fun replayFrom(lastWordsAtMs: Long, nowMs: Long): Long = maxOf(lastWordsAtMs, nowMs - REPLAY_MAX_MS)

    const val REPLAY_MAX_MS = 20_000L

    // ---- Облако не отвечает — дослушать офлайн-пакетом ----
    //
    // Владелец (28.09.2026): «несколько фраз застряли… подозреваю, что он не
    // может достучаться до облачного… можно ли вообще пробовать при
    // застревании перекидывать?». Можно — потому что звук теперь держит
    // Правка (`MicFeed`): офлайн-пакету отдаётся тот же звук с последнего
    // разобранного слова, и перекидывание ничего не теряет. Два трека сразу
    // (облако и пакет параллельно) не делаем: служба у них, скорее всего,
    // одна и держит одну сессию, батарея вдвое, а выбрать «верный» из двух
    // по-разному нарезанных текстов без отметок времени у слов нечем.

    // Коды SpeechRecognizer: NETWORK_TIMEOUT = 1, NETWORK = 2, SERVER = 4,
    // TOO_MANY_REQUESTS = 10 — все про дорогу до облака, не про микрофон.
    private val CLOUD_CODES = setOf(1, 2, 4, 10)

    /** Ошибка — дорога до облака (сеть, сервер), а не микрофон и не тишина. */
    fun cloudLost(code: Int): Boolean = code in CLOUD_CODES

    /** Застрял столько раз подряд на облаке — дальше офлайн-пакет. */
    const val STUCK_BEFORE_OFFLINE = 2

    /**
     * Перекинуть тейк на офлайн-пакет: идём облаком, пакет на телефоне есть,
     * и облако подвело — ошибка дороги ([cloudLost]), второй раз подряд
     * застрял, перестал читать звук ([stalled]) или молчит ([silent]:
     * не сказал «готов» за [CLOUD_READY_MS] или [CLOUD_MUTE_MS] речи не
     * отдал ни слова).
     */
    fun toOffline(
        onCloud: Boolean,
        offlineAvailable: Boolean,
        cloudError: Boolean,
        stuckRestarts: Int,
        stalled: Boolean,
        headsetRefused: Boolean = false,
        silent: Boolean = false,
    ): Boolean = onCloud && offlineAvailable &&
        (cloudError || stalled || headsetRefused || silent || stuckRestarts >= STUCK_BEFORE_OFFLINE)

    // ---- Облако молчит: сети нет, а ошибки тоже нет ----
    //
    // Владелец (01.10.2026): «в моменты, когда нет интернета, микрофон прямо
    // застревает… если там не отвечает одну или 2 секунды Google, то, может
    // быть, 3, то надо переключаться на обычный и при этом ещё и делать фид той
    // части звука, которая не записалась… завис на минут 10… пока я не
    // догадался, что надо включить-выключить VPN». С VPN сеть у телефона ЕСТЬ
    // (туннель поднят), а дороги нет: облако не падает ошибкой сети, оно ждёт —
    // не говорит «готов», не читает звук или читает и молчит. Прежние сторожа
    // ждали от него ошибки или событий речи и не дожидались, и тейк висел до
    // десяти минут без слов. Теперь молчание судим сами — по своей записи.

    /** Облачная сессия не сказала «готов» столько после старта — облако не отвечает. */
    const val CLOUD_READY_MS = 2_500L

    /**
     * Столько речи (своя запись слышит голос) без единого нового слова от
     * облака — оно молчит. Живое облако отдаёт первые слова за полсекунды-
     * секунду речи, через VPN — за полторы.
     */
    const val CLOUD_MUTE_MS = 3_000L

    /** Громкость (0..1, `MicLevel`) от этой — голос, а не тишина комнаты. */
    const val VOICED_LEVEL = 0.4f

    /** Кусок громкости длиннее этого в счёт речи не идёт целиком: сторож опоздал — не досчитывать. */
    const val VOICED_STEP_MAX_MS = 200L

    /** Громкость [level] — это голос. */
    fun voiced(level: Float): Boolean = level >= VOICED_LEVEL

    /**
     * Облако молчит: [voicedMs] речи с последнего слова, и с самого слова
     * прошло не меньше того же ([sinceWordsMs]) — голос был, слов нет.
     */
    fun cloudMute(voicedMs: Long, sinceWordsMs: Long): Boolean =
        voicedMs >= CLOUD_MUTE_MS && sinceWordsMs >= CLOUD_MUTE_MS

    /**
     * Облако подвело на этой сети — столько следующие тейки идут сразу
     * офлайн-пакетом, не тратя на него первые секунды: «ни перезагрузка
     * микрофона не помогала» — каждый новый тейк упирался в то же молчание.
     * Сменилась сеть (включил-выключил VPN, ушёл с Wi-Fi) — облако пробуем
     * сразу.
     */
    const val CLOUD_DEAD_TTL_MS = 5L * 60 * 1000

    /** Начать тейк офлайн-пакетом: облако молчало в [deadAtMs] на той же сети ([sameNetwork]), и это свежо. */
    fun cloudStillDead(deadAtMs: Long, nowMs: Long, sameNetwork: Boolean): Boolean =
        deadAtMs > 0L && sameNetwork && nowMs - deadAtMs in 0 until CLOUD_DEAD_TTL_MS

    // ---- Берёт ли распознаватель звук Правки ----
    //
    // Журнал 29.09: весь день «этот путь звук Правки не берёт», каждый тейк в
    // наушниках шёл прежней дорогой, и через 5–12 с Android снимал канал
    // гарнитуры — «отваливается микрофон на наушниках», и слова глотались
    // телефоном на столе. А накануне переключение работало: облако звук
    // брало. Один отказ, вынесенный за 2,2 с (через VPN облако начинает читать
    // и позже), выключал свою запись до перезапуска приложения.

    /** Не читает звук столько после «готов» — только тогда считать, что не читает. */
    const val FEED_PROOF_WAIT_MS = 5_000L

    /** Отказ пути (открыл свой микрофон) помнится столько, потом пробуем снова. */
    const val FEED_REFUSAL_TTL_MS = 30L * 60 * 1000

    /** Отказ, вынесенный в [refusedAtMs], ещё в силе в [nowMs]. */
    fun feedRefusalLive(refusedAtMs: Long, nowMs: Long): Boolean =
        nowMs - refusedAtMs in 0 until FEED_REFUSAL_TTL_MS

    /**
     * Начать тейк сразу офлайн-пакетом: слушать велено наушники, облако звук
     * Правки не берёт (отказ в силе), а пакет — не отказывал. Наушники без
     * своей записи держатся секунды, и тейк услышал бы телефон на столе:
     * пакет в наушниках лучше облака без них.
     */
    fun headsetToOffline(
        wantHeadset: Boolean,
        onCloud: Boolean,
        cloudRefused: Boolean,
        offlineAvailable: Boolean,
        offlineRefused: Boolean,
    ): Boolean = wantHeadset && onCloud && cloudRefused && offlineAvailable && !offlineRefused

    // ---- Своя запись: звука нет или одни нули ----

    /** Ровные нули столько подряд — канал молчит (наушники без звука, вход отдан другому). */
    const val DEAD_AIR_MS = 2_000L

    /** Наушники молчат столько даже после повторного подъёма канала — обратно на телефон. */
    const val DEAD_AIR_GIVE_UP_MS = 5_000L

    /** Запись не отдаёт звук столько — разбудить её. */
    const val CAPTURE_STALL_MS = 2_500L

    /** Не оживает столько — отдать микрофон распознавателю, пусть слушает сам. */
    const val CAPTURE_GIVE_UP_MS = 8_000L

    // ---- Наушники: чья это кнопка, хвост после стопа ----

    /**
     * Канал гарнитуры закрыла её кнопка — столько после этого смена входа
     * записи на телефон считается стопом на подходе, а не «наушники
     * отвалились». Стоп приходит через 0,7 с (проверка на «моргнул»), запас — с лихвой.
     */
    const val HEADSET_STOP_GRACE_MS = 2_500L

    /** Смена входа в [nowMs] — следствие того, что канал закрыла кнопка в [closedAtMs]. */
    fun headsetStopPending(closedAtMs: Long, nowMs: Long): Boolean =
        closedAtMs > 0L && nowMs - closedAtMs in 0 until HEADSET_STOP_GRACE_MS

    /** Что значит вход своей записи, сам ушедший с наушников на телефон посреди тейка. */
    enum class HeadsetDrop {
        /** Стек уже сказал, что канал закрыла кнопка: стоп идёт своей дорогой. */
        STOP_PENDING,

        /** Наушники на связи, а канала нет: его закрыла их кнопка — это стоп. */
        BUTTON_STOP,

        /** Наушников нет (сели, ушли из зоны) или тейк только встаёт: слушает телефон. */
        LOST,
    }

    /**
     * Вход ушёл с наушников на телефон — чья это рука (владелец, 30.09.2026:
     * «когда я нажимаю в конце долго кнопку… он просто говорит „наушники
     * отвалились“ и не отсылает то, что уже можно расшифровывать»).
     *
     * Запись замечает смену входа по себе, а стек Bluetooth присылает «канал
     * закрыт» рассылкой — и она то приходит раньше записи, то позже (или не
     * приходит вовсе: распознавание не подтверждено, и стек, отказав кнопке в
     * помощнике, роняет канал сам). Поэтому решает не только [closedAtMs]:
     * гарнитура по-прежнему подключена ([stillConnected]), а канал к ней пропал —
     * значит, его закрыли её кнопкой, и тейку пора кончаться со сказанным.
     * Настоящее «отвалились» — это когда гарнитуры нет и среди подключённых.
     *
     * Первые [HEADSET_BUTTON_MIN_MS] наушников ([heardFromMs] — когда их вход
     * встал) — не стоп: на старте канал делят стек и тейк, и он моргает.
     */
    fun headsetDrop(closedAtMs: Long, nowMs: Long, stillConnected: Boolean, heardFromMs: Long): HeadsetDrop = when {
        headsetStopPending(closedAtMs, nowMs) -> HeadsetDrop.STOP_PENDING
        stillConnected && heardFromMs > 0L && nowMs - heardFromMs >= HEADSET_BUTTON_MIN_MS -> HeadsetDrop.BUTTON_STOP
        else -> HeadsetDrop.LOST
    }

    /** Сколько наушники должны прослушать, чтобы пропавший канал читался их кнопкой, а не стартом. */
    const val HEADSET_BUTTON_MIN_MS = 2_000L

    /**
     * Сколько ждать после пропажи канала, прежде чем остановить тейк: канал,
     * вернувшийся за это время, моргнул. Как проверка на «моргнул» у стека.
     */
