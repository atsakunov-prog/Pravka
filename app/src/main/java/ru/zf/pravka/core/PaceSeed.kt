package ru.zf.pravka.core

import ru.zf.pravka.data.ModelRoute
import ru.zf.pravka.data.Models
import ru.zf.pravka.data.Settings

/**
 * С чего дуга прогресса начинает, пока своих замеров на дороге нет, и что в
 * журнале приложения считать замером.
 *
 * Владелец (20.09.2026): «ты не взял всю статистику, а только начал её
 * собирать. Посмотри, в аппе есть логи, значит, вся информация есть… Посчитай
 * сейчас среднее исходя из этих данных и пускай тогда само приложение считает
 * дальше». Так и сделано, в два слоя:
 *
 *  1. Журнал правок (`data/HistoryLog`) приложение читает САМО, один раз после
 *     обновления, и складывает оттуда настоящие замеры — там лежат модель,
 *     время ответа и надиктованный текст, то есть ровно то, из чего строится
 *     прямая. Это дорога «Правка»: журнал ведётся только на ней.
 *  2. Дороги, по которым журнала нет (Засечка, Разноска, Тело, Еда),
 *     начинают с заводской прикидки ниже — или с прямой своей же дороги на
 *     другой модели, пересчитанной через эти же числа ([transfer]).
 *
 * Числа — по журналу правок владельца, 27.07–26.09.2026 (1862 чистки),
 * наименьшие квадраты с отброшенными 10% худших выбросов (пересчёт 26.09):
 *
 * | модель            | замеров | основание | на знак | 40 зн. | 140 зн. | 600 зн. |
 * |-------------------|---------|-----------|---------|--------|---------|---------|
 * | Сонет 5           |   1 538 |   1,9 с   |  4,5 мс |  2,1 с |  2,6 с  |  4,6 с  |
 * | Опус 5 (усилие менялось) | 174 | 2,2 с |  13,2 мс |  2,7 с |  4,0 с  | 10,1 с  |
 * | Опус 5.5, medium  |     150 |   3,2 с   | 14,2 мс |  3,7 с |  5,2 с  | 11,7 с  |
 *
 * Откуда разница — видно по токенам (владелец: «может, где-то взять взаимные
 * коэффициенты?»). Время ≈ СТАРТ + токены выхода / скорость. Старт у всех
 * трёх один — около 1,9 с (сеть, чтение промпта, первый токен). Скорость —
 * своя: Сонет ≈ 98 токенов в секунду, Опус 5 ≈ 77, Опус 5.5 ≈ 115 — он
 * генерирует БЫСТРЕЕ Сонета. Но токенов у него больше: у Сонета размышлений
 * нет, и на знак текста выходит 0,45 токена, а Опус 5.5 на medium думает
 * ≈ 160 токенов на старте плюс около токена на каждый знак. Отсюда
 * отношение «Опус 5.5 / Сонет» — не одно число, а растёт с длиной: 1,8 на
 * коротких фразах, 2,0 на средней, 2,5 на длинных. Поэтому переносить
 * прямую с модели на модель надо ДВУМЯ коэффициентами — на основание и на
 * знак ([transfer]), одним множителем длинные фразы врали бы.
 *
 * Усилие журнал правок не пишет, но его след в нём есть — размышления:
 * у Опуса 5 они скакали по дням от 7 до 260 токенов на запрос (владелец
 * менял усилие), у Опуса 5.5 ровно 320–400 (medium). Поэтому у каждой
 * строки своё [Guess.effort] — на каком усилии она снята, — и остальные
 * усилия считаются от него множителями [effortFactor].
 *
 * Холодный кэш на Правке не стоит ничего (остаток холодных запросов в
 * пределах шума у всех трёх моделей), контекст поля — тоже. Смена
 * распознавателя (Google на телефоне на облачный) времени Claude не
 * меняет: он получает текст, а длина текста и так в прямой.
 *
 * Fable своих замеров не имеет: на дорогах, где видны секунды, он не
 * работает (ночные разборы идут батчами без окна). Число ниже — прикидка
 * между Сонетом и Опусом, и живёт она ровно до первых своих замеров.
 */
object PaceSeed {

    /** Прямая «основание + столько-то на знак» для одной модели, снятая на усилии [effort]. */
    data class Guess(val baseMs: Double, val msPerChar: Double, val effort: String = "high")

    /** Сколько последних записей журнала брать: дальше вес всё равно гаснет. */
    const val HISTORY_TAIL = 400

    private val OPUS = Guess(3_170.0, 14.2, "medium")
    private val OPUS_5 = Guess(2_170.0, 13.2, "high")
    private val SONNET = Guess(1_930.0, 4.5, "high")
    private val FABLE = Guess(1_800.0, 9.0, "high")

    private val BY_MODEL = mapOf(
        Settings.MODEL_OPUS to OPUS,
        Settings.MODEL_OPUS_5 to OPUS_5,
        Settings.MODEL_SONNET to SONNET,
        Settings.MODEL_FABLE to FABLE,
    )

    /**
     * Незнакомая модель — как Сонет: из трёх заводских дорог он посередине, и
     * ошибиться на нём вдвое дешевле, чем обещать всем скорость Опуса.
     */
    fun guess(model: String): Guess = BY_MODEL[model] ?: SONNET

    /**
     * Во сколько раз усилие растягивает ожидание против high. Замеры Опуса в
     * таблице выше сняты на high («по умолчанию» у Опуса 5), Сонета — без
     * размышлений. Сами множители — прикидка, не замер (22.09.2026, владелец:
     * «в прогресс-баре чтобы учитывалась модель и усилие»): мысли на xhigh у
     * Опуса 5.5 длятся заметно дольше, чем на medium, и одна прямая на все
     * усилия врала бы в обе стороны. Живут они, как и вся прикидка, до своих
     * замеров на тройке «дорога + модель + усилие».
     */
    fun effortFactor(model: String, effort: String): Double {
        val e = Models.effectiveEffort(model, effort)
        // Сонет до high отвечает без размышлений — усилие ему время не меняет.
        if (model == Settings.MODEL_SONNET && e !in setOf("xhigh", "max")) return 1.0
        return when (e) {
            "low" -> 0.6
            "medium" -> 0.8
            "xhigh" -> 1.5
            "max" -> 2.2
            else -> 1.0
        } * if (model == Settings.MODEL_SONNET) 2.0 else 1.0
    }

    /** Прямая модели на усилии [effort]: снятая строка, растянутая от своего усилия к нужному. */
    fun line(model: String, effort: String = ""): Guess = guess(model).let {
        val f = effortFactor(model, effort) / effortFactor(model, it.effort)
        Guess(it.baseMs * f, it.msPerChar * f, Models.effectiveEffort(model, effort))
    }

    /** Заводской накопитель дороги: та же прямая, весом в несколько замеров, с поправкой на усилие. */
    fun prior(model: String, effort: String = ""): Pace.Acc = line(model, effort).let {
        Pace.prior(it.baseMs, it.msPerChar)
    }

    /**
     * Взаимные коэффициенты (владелец, 26.09.2026: «может, где-то взять
     * взаимные коэффициенты? Мол, опус на том же объёме будет в 1.2 раза
     * медленнее»). Прямая [known], выученная дорогой на модели [fromModel]
     * с усилием [fromEffort], — на модель [toModel] с усилием [toEffort]:
     * основание и цена знака множатся КАЖДОЕ на своё отношение заводских
     * прямых (из журнала правок, где одну и ту же работу делали все модели).
     * Одним числом нельзя: «Опус 5.5 / Сонет» — 1,8 на короткой фразе и 2,5
     * на длинной. Своя форма дороги (JSON у Засечки, абзацы у тренера)
     * остаётся, меняется только модель.
     */
    fun transfer(known: Pace.Line, fromModel: String, fromEffort: String, toModel: String, toEffort: String): Pace.Acc {
        val from = line(fromModel, fromEffort)
        val to = line(toModel, toEffort)
        val baseK = to.baseMs / from.baseMs
        val charK = to.msPerChar / from.msPerChar
        if (known.straight) {
            return Pace.prior((known.baseMs * baseK).coerceAtLeast(Pace.MIN_MS.toDouble()), known.msPerChar * charK)
        }
        // Длины у соседки ещё нет — одно среднее: переносим его уровень на
        // типичной фразе, а наклон берём заводской у новой модели.
        val typical = TYPICAL_CHARS
        val whole = (to.baseMs + to.msPerChar * typical) / (from.baseMs + from.msPerChar * typical)
        val level = known.meanMs * whole
        return Pace.prior((level - to.msPerChar * typical).coerceAtLeast(Pace.MIN_MS.toDouble()), to.msPerChar)
    }

    /** Медиана длины фразы владельца (журнал распознавания, 1790 диктовок). */
    const val TYPICAL_CHARS = 134.0

    /** Модели с заводской прикидкой — строкой для настроек, по убыванию цены знака. */
    fun factoryLine(): String = BY_MODEL.entries
        .sortedByDescending { it.value.msPerChar }
        .joinToString(" · ") { (model, g) ->
            "%s %s %.1f с + %.1f".format(java.util.Locale.US, shortModel(model), g.effort, g.baseMs / 1000.0, g.msPerChar)
        }

    /** «claude-opus-5-5» → «opus-5-5»: в настройках читается, а место экономит. */
    fun shortModel(model: String): String = model.removePrefix("claude-").ifBlank { model }

    /**
     * Какой дороге принадлежит запись журнала правок. В журнале стоит режим
     * (CLEAN, BUSINESS, SOFTEN, ASSIST_*), а дорога у всех у них одна: и
     * чистка, и помощник ходят моделью [ModelRoute.PRAVKA]. Чужой режим —
     * null: лучше не знать, чем записать замер не на ту дорогу.
     *
     * Кнопку «сильнее» журнал не отмечает, и её замеры ложатся сюда же. Это
     * сознательно: за три месяца её видно единицы раз, а своя дорога у неё
     * наберёт замеры за день работы и прикидку вытеснит.
     */
    fun route(mode: String): String? = when {
        mode == "CLEAN" || mode == "BUSINESS" || mode == "SOFTEN" -> ModelRoute.PRAVKA.key
        mode.startsWith("ASSIST_") -> ModelRoute.PRAVKA.key
        else -> null
    }

    /**
     * Замер засчитывается только моделям Claude: дуга показывает ожидание
     * запроса по сети, а `gemini-nano` (опыт, закрытый в августе) считал на
     * самом телефоне и никакого отношения к этому ожиданию не имеет.
     */
    fun counts(model: String): Boolean = model.startsWith("claude-")
}
