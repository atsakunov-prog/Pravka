package ru.zf.pravka.core

/**
 * Цвет категории ленты в виде v2 — «чей это», палитра `--sp0…--sp7` общего слоя
 * Ковчега (Правка 5.0; владелец 13.10.2026, глядя на «Сегодня» со светофором:
 * «нравилась гамма как на макетах, а не светофор»). Одна функция на гору дня,
 * полосу суток, квадратики ленты, легенду — и на Засечку и итоги дня, когда они
 * переедут в v2. «Вид 4.0» красит по-старому (светофор цены часа, `categoryFill`).
 *
 * Цвет — по верхнему уровню категории (до двоеточия): «Работа: текущая» и
 * «Работа: звонки» — один цвет, как на холсте. Свои места у восьми названий
 * холста; дорога — серый пополам с фоном, потери — оранжевый пополам с фоном
 * (бледные: время, которое не про дело), «не размечено» — дыра цветом линии.
 * Остальные — устойчиво по имени: то же имя — тот же цвет на любом телефоне и
 * после перезапуска (`String.hashCode` задан языком, а не процессом).
 */
object CategoryTone {

    /** Сколько цветов в палитре «чей это». */
    const val SIZE = 8

    /**
     * Тон: [sp] — номер цвета палитры; [half] — пополам с фоном (дорога,
     * потери); [gap] — «не размечено», рисуется цветом линии, а не палитрой.
     */
    data class Tone(val sp: Int, val half: Boolean = false, val gap: Boolean = false)

    /** Места холста: верхний уровень категории → номер цвета. */
    private val FIXED = mapOf(
        "работа" to 0,
        "быт" to 1,
        "спорт" to 2,
        "семья" to 3,
        "отдых" to 4,
        "систематизация" to 5,
        "еда" to 6,
        "сон" to 7,
    )

    /** Дорога: и «Передвижение: …» владельца, и «Дорога» холста. */
    private val ROAD = setOf("передвижение", "дорога")

    /** Верхний уровень имени: до двоеточия, без регистра и пробелов по краям. */
    fun top(category: String): String = category.substringBefore(':').trim().lowercase()

    fun of(category: String): Tone {
        val top = top(category)
        return when {
            top == "не размечено" -> Tone(7, gap = true)
            // Без категории — нейтральный серый, а не цвет работы у пустой строки.
            top.isEmpty() -> Tone(7)
            top in ROAD -> Tone(7, half = true)
            top == "потери" -> Tone(6, half = true)
            else -> FIXED[top]?.let { Tone(it) } ?: Tone(Math.floorMod(top.hashCode(), SIZE - 1))
        }
    }
}
