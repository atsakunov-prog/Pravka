package ru.zf.pravka.core

/**
 * Громкость микрофона в размер кнопки. Владелец (20.09.2026): «кнопка должна
 * пульсировать в ритме звуков, если слышит».
 *
 * Пульс идёт ВНУТРЬ, а не наружу, и это та же геометрия, из-за которой кнопка
 * под пальцем сжимается: оверлейное окно ровно с кружок, и всё, что вылезло за
 * единицу, окно отрезает — круг стал бы квадратом по краям. Поэтому на время
 * записи кнопка поджимается до [QUIET] и РАСПРЯМЛЯЕТСЯ от звука до единицы.
 * Глаз читает это как «раздувается от голоса», хотя наружу не растёт ничего.
 */
object MicLevel {

    /** Размер кнопки в тишине во время записи: есть куда расти. */
    const val QUIET = 0.90f

    /** Ниже этого в децибелах — тишина. SpeechRecognizer отдаёт примерно −2…10. */
    const val FLOOR_DB = -2f

    /** Выше этого — уже полная громкость; дальше шкалу не растягиваем. */
    const val CEILING_DB = 8f

    /** Децибелы распознавателя в долю 0..1. */
    fun normalise(rmsDb: Float): Float {
        if (rmsDb.isNaN()) return 0f
        return ((rmsDb - FLOOR_DB) / (CEILING_DB - FLOOR_DB)).coerceIn(0f, 1f)
    }

    /** Доля громкости в масштаб кнопки. */
    fun scale(level: Float): Float = QUIET + (1f - QUIET) * level.coerceIn(0f, 1f)

    /**
     * Сглаживание: новая доля тянет старую на [RISE] вверх и на [FALL] вниз.
     * Вверх быстрее, чем вниз, — так делают все стрелочные индикаторы
     * громкости, и по той же причине: удар слышен сразу, а спад глаз
     * додумывает. Без сглаживания кнопка дрожала бы: замеры приходят раз в
     * десятую секунды, и между ними шкала прыгает.
     */
    fun smooth(previous: Float, target: Float): Float {
        val t = target.coerceIn(0f, 1f)
        val k = if (t > previous) RISE else FALL
        return previous + (t - previous) * k
    }

    private const val RISE = 0.7f
    private const val FALL = 0.25f
}
