package ru.zf.pravka.core

/**
 * Геометрия стопки плавающих кнопок: «П», под ней плашка микрофона, дальше
 * «З», «Д», «Т». Одно место для арифметики, которая раньше была размазана по
 * девяти обработчикам перетаскивания в службе: каждый считал `y + size + gap`
 * сам, и вставить между «П» и «З» что-нибудь ещё значило бы править все девять.
 *
 * Плашка микрофона живёт в своём слоте между «П» и «З». Первая версия была
 * кружком в треть кнопки (владелец, 13.09.2026: «иконка размером в треть от
 * них») — и в него не попадалось: «совсем маленькая, у меня просто не
 * получается по ней попасть». Теперь это прямоугольник со скруглёнными углами
 * на всю ширину кнопки и в половину её высоты, тап-зона — весь слот.
 */
object StackGeometry {

    /** Высота плашки — половина кнопки; ширина — как у кнопки. */
    fun toggleHeight(buttonSize: Int): Int = buttonSize / 2

    /** Высота слота плашки между «П» и «З»: сама плашка и поля с двух сторон. */
    fun toggleSlot(buttonSize: Int, pad: Int): Int = toggleHeight(buttonSize) + 2 * pad

    /**
     * Смещение верха кнопки в слоте [slot] от верха «П»: 0 — «П», 1 — «З»,
     * 2 — «Д», 3 — «Т». Между «П» и «З» — [zGap] (слот плашки), между
     * остальными — обычный [gap].
     */
    fun slotOffset(slot: Int, size: Int, gap: Int, zGap: Int): Int =
        if (slot <= 0) 0 else size + zGap + (slot - 1) * (size + gap)
}
