package ru.zf.pravka.core

/**
 * Геометрия стопки плавающих кнопок: шестерёнка над «П», под ней «П», «З»,
 * «Д», «Т», под хвостом — ручка-галочка. Одно место для арифметики, которая
 * раньше была размазана по девяти обработчикам перетаскивания в службе.
 *
 * Плашки микрофона между «П» и «З» больше нет (владелец, 18.09.2026:
 * «убираем грязь из стекла кнопок: наушники и верхнюю с тремя точками») —
 * переключатель микрофона переехал в веер шестерёнки, а просвет между
 * кнопками снова одинаковый.
 */
object StackGeometry {

    /** Смещение верха кнопки в слоте [slot] от верха «П»: 0 — «П», 1 — «З», 2 — «Д», 3 — «Т». */
    fun slotOffset(slot: Int, size: Int, gap: Int): Int =
        if (slot <= 0) 0 else slot * (size + gap)

    /**
     * Шестерёнка над «П» и кружки её веера — в 0,72 кнопки. Меньше нельзя:
     * плашка микрофона в треть кнопки не прожила и дня («совсем маленькая, не
     * получается по ней попасть»), а по кружкам веера жмут так же часто.
     */
    fun gearSize(buttonSize: Int): Int = (buttonSize * 0.72f).toInt()

    /**
     * Красная точка, в которую сжимается всё, когда кнопки убраны: 0,42
     * кнопки. Достаточно, чтобы попасть и утащить, и мало, чтобы не мешать.
     */
    fun dotSize(buttonSize: Int): Int = (buttonSize * 0.42f).toInt()

    /**
     * Левый край веера из [count] кружков размером [bubble] с просветом
     * [gap], раскрытого от шестерёнки с левым краем [gearX] и размером
     * [gearSize] на экране шириной [screenW]: в ту сторону, где есть место
     * (стопка у правого края — веер влево), и не дальше края экрана.
     */
    fun fanX(gearX: Int, gearSize: Int, count: Int, bubble: Int, gap: Int, screenW: Int): Int {
        val width = count * bubble + (count - 1) * gap
        val centre = gearX + gearSize / 2
        val x = if (centre < screenW / 2) gearX + gearSize + gap else gearX - gap - width
        return x.coerceIn(0, (screenW - width).coerceAtLeast(0))
    }
}
