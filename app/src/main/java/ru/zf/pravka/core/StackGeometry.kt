package ru.zf.pravka.core

/**
 * Геометрия стопки плавающих кнопок: «П», под ней значок микрофона, дальше
 * «З», «Д», «Т». Одно место для арифметики, которая раньше была размазана по
 * девяти обработчикам перетаскивания в службе: каждый считал `y + size + gap`
 * сам, и вставить между «П» и «З» что-нибудь ещё значило бы править все девять.
 *
 * Значок микрофона (владелец, 13.09.2026: «между правкой и засечкой будет
 * иконка размером в треть от них») живёт в своём слоте: кружок в треть кнопки
 * и по [pad] сверху и снизу. Тап-зона — весь слот, иначе в 16 dp не попасть.
 */
object StackGeometry {

    /** Диаметр кружка значка — треть кнопки. */
    fun toggleSize(buttonSize: Int): Int = buttonSize / 3

    /** Высота слота значка между «П» и «З»: кружок и поля с двух сторон. */
    fun toggleSlot(buttonSize: Int, pad: Int): Int = toggleSize(buttonSize) + 2 * pad

    /**
     * Смещение верха кнопки в слоте [slot] от верха «П»: 0 — «П», 1 — «З»,
     * 2 — «Д», 3 — «Т». Между «П» и «З» — [zGap] (слот значка), между
     * остальными — обычный [gap].
     */
    fun slotOffset(slot: Int, size: Int, gap: Int, zGap: Int): Int =
        if (slot <= 0) 0 else size + zGap + (slot - 1) * (size + gap)
}
