package ru.zf.pravka.provider

import ru.zf.pravka.data.Settings

/**
 * Форма запроса в зависимости от модели и усилия — в одном месте, без
 * Android-зависимостей, чтобы её проверял JVM-тест.
 *
 * Почему это не просто `model == Сонет`:
 * - На Сонете чистка диктовки идёт без размышлений: правка — механика, мысли
 *   только добавляют секунды и деньги. Но если владелец сам выставил усилие
 *   xhigh или max, он хочет глубины — тогда размышления включаются
 *   (адаптивные, параметр опускается).
 * - Выключаются мысли у Сонетов по-разному. Сонет 5.5 (с 30.09.2026) на
 *   `thinking: disabled` отвечает 400 — у него самое низкое положение
 *   `between_tools`: без размышлений, только короткие заметки между вызовами
 *   инструментов (инструментов у нас нет). Оно живёт только до high — на
 *   xhigh/max тоже 400, — и больше никакая модель его не принимает. Прежний
 *   Сонет 5 — наоборот, понимает только `disabled`: батчи, отправленные
 *   старой сборкой, и выбор, застрявший в хранилище, должны пройти.
 * - На Опусе 5 явное «disabled» вместе с xhigh/max отвергается с 400, а на
 *   меньших усилиях имеет документированные сбои (вызов инструмента текстом,
 *   утечка тегов). На Fable и Опусе 5.5 размышления выключить нельзя вовсе —
 *   400 на любом усилии.
 *   Поэтому вне Сонета параметр не передаётся никогда: адаптивные мысли —
 *   их поведение по умолчанию, глубину задаёт усилие.
 */
object RequestPolicy {

    /** Усилия, при которых размышления нужны даже Сонету. */
    private val deepEfforts = setOf("xhigh", "max")

    private val sonnets = setOf(Settings.MODEL_SONNET, Settings.MODEL_SONNET_5)

    fun thinkingOff(model: String, effort: String): Boolean =
        model in sonnets && effort.trim() !in deepEfforts

    /**
     * Что положить в `thinking.type`, чтобы выключить размышления, или null —
     * поле не передавать. Одно место на все запросы: дневной, батчи, словарь.
     */
    fun thinkingOffType(model: String, effort: String): String? = when {
        !thinkingOff(model, effort) -> null
        model == Settings.MODEL_SONNET_5 -> "disabled"
        else -> "between_tools"
    }

    /**
     * Запас под мысли в max_tokens. Размышления считаются в тот же бюджет, и
     * без запаса короткая переделка сжигала его целиком на мыслях и умирала
     * с stop_reason=max_tokens, не выдав ни слова (18.08.2026).
     */
    fun thinkingHeadroom(model: String, effort: String): Int = when {
        thinkingOff(model, effort) -> 0
        // Засечка и еда с 22.09.2026 на xhigh: восьми тысяч на мысли над
        // снимком тарелки и справочниками может не хватить.
        effort.trim() in deepEfforts -> 16_000
        else -> 8000
    }

    /**
     * Запас под мысли в батче. Дневной запрос ограничен временем ожидания и
     * потоком, батчу спешить некуда, а Fable на high над пакетом свидетельств
     * за сутки думает больше восьми тысяч токенов: первый прогон ночного
     * разбора (16.09.2026) упёрся в max_tokens и вернул JSON, обрезанный на
     * середине, — отчёт пришёл красной простынёй вместо изменений.
     */
    fun batchThinkingHeadroom(model: String, effort: String): Int = when {
        thinkingOff(model, effort) -> 0
        // Разборы с 22.09.2026 — Опус 5.5 на max. 64 тысяч не хватало: оба
        // недельных разбора Опуса (02.10, 09.10) вернули ровно 72 000 токенов
        // выхода — весь потолок ушёл на мысли над пачкой в 80 тысяч токенов,
        // ответа не было, ~75 центов за раз в никуда. Max — до потолка модели
        // (128K у Опуса 5.5, Сонета 5.5 и Fable).
        effort.trim() == "max" -> MAX_OUTPUT_TOKENS
        // Ступени ниже — с запасом: за неиспользованный потолок не платим, а
        // повтор после обрезки на max должен успеть ответить.
        effort.trim() == "xhigh" -> 96_000
        effort.trim() == "high" -> 48_000
        else -> 32_000
    }

    /** Потолок выхода у нынешних моделей (Опус 5.5, Сонет 5.5, Fable 5.1 — 128K): больше — 400. */
    const val MAX_OUTPUT_TOKENS = 128_000

    /** Бюджет ответа в батче: ответ плюс запас на мысли, но не выше потолка модели. */
    fun batchMaxTokens(model: String, effort: String, answerTokens: Int): Int =
        (answerTokens + batchThinkingHeadroom(model, effort)).coerceAtMost(MAX_OUTPUT_TOKENS)

    /**
     * Ступенька вниз, когда ответ батча обрезан по длине: мысли съели весь
     * потолок. Повтор на ступень ниже по тем же свидетельствам (они в кэше)
     * дешевле пустого прогона, а max → xhigh → high — дальше не спускаемся:
     * ниже high разбор недели теряет смысл. Пусто — вниз некуда.
     */
    fun lowerEffort(effort: String): String? = when (effort.trim()) {
        "max" -> "xhigh"
        "xhigh" -> "high"
        else -> null
    }

    /**
     * Бюджет ответа для правки текста: грубая оценка токенов входа по длине
     * (~2,5 знака на токен у русского, считаем половину знаков) + 30 % запаса
     * + место под мысли; снимок тарелки — ещё ~1600 токенов на картинку.
     * Одна формула на дневной запрос и на батч (тень второй модели, эвал):
     * обрезка по длине должна случаться в обоих одинаково, иначе сравнение
     * моделей мерит не модель, а разницу бюджетов.
     */
    fun maxTokens(model: String, effort: String, variableChars: Int, images: Int = 0): Int {
        val estimatedInputTokens = variableChars / 2 + 1 + images * 1600
        val headroom = thinkingHeadroom(model, effort)
        // Потолок растёт на добавку xhigh сверх обычных восьми тысяч: иначе
        // лишние мысли съели бы место самого ответа на длинном тексте. Сонету
        // без мыслей потолок прежний — 16384.
        return (estimatedInputTokens * 13 / 10 + 300 + headroom).coerceIn(1024, 16384 + (headroom - 8000).coerceAtLeast(0))
    }
}
