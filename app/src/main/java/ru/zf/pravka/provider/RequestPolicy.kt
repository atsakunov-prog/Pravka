package ru.zf.pravka.provider

import ru.zf.pravka.data.Settings

/**
 * Форма запроса в зависимости от модели и усилия — в одном месте, без
 * Android-зависимостей, чтобы её проверял JVM-тест.
 *
 * Почему это не просто `model == Сонет`:
 * - На Сонете чистка диктовки идёт без размышлений (`thinking: disabled`):
 *   правка — механика, мысли только добавляют секунды и деньги. Но если
 *   владелец сам выставил усилие xhigh или max, он хочет глубины — тогда
 *   размышления включаются (адаптивные, параметр опускается).
 * - На Опусе 5 явное «disabled» вместе с xhigh/max отвергается с 400, а на
 *   меньших усилиях имеет документированные сбои (вызов инструмента текстом,
 *   утечка тегов). На Fable размышления выключить нельзя вовсе — тоже 400.
 *   Поэтому вне Сонета параметр не передаётся никогда: адаптивные мысли —
 *   их поведение по умолчанию, глубину задаёт усилие.
 */
object RequestPolicy {

    /** Усилия, при которых размышления нужны даже Сонету. */
    private val deepEfforts = setOf("xhigh", "max")

    fun thinkingOff(model: String, effort: String): Boolean =
        model == Settings.MODEL_SONNET && effort.trim() !in deepEfforts

    /**
     * Запас под мысли в max_tokens. Размышления считаются в тот же бюджет, и
     * без запаса короткая переделка сжигала его целиком на мыслях и умирала
     * с stop_reason=max_tokens, не выдав ни слова (18.08.2026).
     */
    fun thinkingHeadroom(model: String, effort: String): Int =
        if (thinkingOff(model, effort)) 0 else 8000

    /**
     * Запас под мысли в батче. Дневной запрос ограничен временем ожидания и
     * потоком, батчу спешить некуда, а Fable на high над пакетом свидетельств
     * за сутки думает больше восьми тысяч токенов: первый прогон ночного
     * разбора (16.09.2026) упёрся в max_tokens и вернул JSON, обрезанный на
     * середине, — отчёт пришёл красной простынёй вместо изменений.
     */
    fun batchThinkingHeadroom(model: String, effort: String): Int =
        if (thinkingOff(model, effort)) 0 else 32_000

    /**
     * Бюджет ответа для правки текста: грубая оценка токенов входа по длине
     * (~2,5 знака на токен у русского, считаем половину знаков) + 30 % запаса
     * + место под мысли; снимок тарелки — ещё ~1600 токенов на картинку.
     * Одна формула на дневной запрос и на батч (тень второй модели, эвал):
     * обрезка по длине должна случаться в обоих одинаково, иначе сравнение
     * моделей мерит не модель, а разницу бюджетов.
     */
    fun maxTokens(model: String, effort: String, variableChars: Int, images: Int = 0): Int {
        val estimatedInputTokens = variableChars / 2 + 1 + images * 1600
        return (estimatedInputTokens * 13 / 10 + 300 + thinkingHeadroom(model, effort)).coerceIn(1024, 16384)
    }
}
