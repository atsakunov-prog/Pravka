package ru.zf.pravka.trigger

/**
 * Кнопка, которую можно поставить на диск (`DiskController`). Четыре
 * контроллера кнопок — четыре класса без общего предка (так сложилось), а
 * диску от каждого нужно одно и то же: где она, поставить её на кольцо,
 * снять с экрана целиком уехавшую за край и услышать палец, который крутит
 * диск за неё.
 */
interface RingButton {

    fun buttonSizePx(): Int

    /** Левый верхний угол окна кнопки, или null, пока кнопки нет. */
    fun currentPosition(): Pair<Int, Int>?

    /** Окно кнопки висит в WindowManager — кнопку видно (спрятанная и убранная — нет). */
    fun onScreen(): Boolean

    /**
     * Где кнопка на экране, если её видно, — препятствие для пилюли
     * диктовки снизу (`DictationPill`): накрывать кнопки ей нельзя.
     */
    fun shownBox(): ru.zf.pravka.core.PillGeometry.Box? {
        if (!onScreen()) return null
        val (x, y) = currentPosition() ?: return null
        val s = buttonSizePx()
        return ru.zf.pravka.core.PillGeometry.Box(x, y, x + s, y + s)
    }

    /**
     * Ехать к ([x], [y]). В стопке — на пружине звеном [link]; с [snap] —
     * встать сразу, без пружины: диск ведёт свою анимацию сам, кадр в кадр,
     * и кнопке остаётся только быть там, где он сказал.
     */
    fun followTo(x: Int, y: Int, settle: Boolean, link: Int = 1, snap: Boolean = false)

    /**
     * Окно кнопки целиком за краем экрана — снять его из WindowManager (и
     * вернуть, когда снова покажется край). Не то же, что «убрана в ручку»:
     * своё поле, чтобы одно не перебивало другое.
     */
    fun setOffscreen(value: Boolean)

    /**
     * Снять и снова повесить окно — поверх окон, добавленных позже. Диск
     * ставит тарелку под кнопки, а порядок окон одного типа — порядок
     * добавления.
     */
    fun reattach()

    /**
     * Кнопка на диске: сама себя не ставит и не тащит, цели `followTo` не
     * режутся краем экрана, окну разрешено выезжать за край.
     */
    var ringMode: Boolean

    /**
     * Палец на кнопке в режиме диска: сырые координаты касания, локальные
     * (внутри окна кнопки) и действие (`MotionEvent.ACTION_DOWN` / `MOVE` /
     * `UP`). Диск считает по ним поворот; кнопка сама не двигается.
     */
    var onRingDrag: ((rawX: Float, rawY: Float, localX: Float, localY: Float, action: Int) -> Unit)?

    /**
     * Диск взяли двумя пальцами — текущее касание этой кнопке больше не
     * принадлежит: ни тапа, ни меню, ни поворота, до следующего касания.
     * Сами события до отпускания кнопка продолжает докладывать диску.
     */
    fun cancelGesture()

    // ---- Связка (стопка) и служба: то, что было у каждого контроллера своё ----

    /** Палец тащит ЭТУ кнопку (стопка): её левый верхний угол; ещё раз — на броске. */
    var onDragged: ((x: Int, y: Int, dropped: Boolean) -> Unit)?

    /** Каждый кадр догонялки: ручка и шестерёнка едут за бусами. */
    var onFrame: (() -> Unit)?

    /**
     * Громкость микрофона 0..1, пока идёт запись. Кнопка пульсирует в ритме
     * звуков (владелец, 20.09.2026: «кнопка должна пульсировать в ритме
     * звуков, если слышит»). Не пишет — молча пропускает: служба раздаёт
     * уровень всем кнопкам сразу, а слышит всегда одна.
     */
    fun setLevel(level: Float)

    /**
     * Запрос к модели ушёл: сколько ждать, по своей истории. Кнопка покажет
     * секунды вместо колеса, если занята она (`ButtonCountdown`); свободная
     * запомнит и промолчит. Приходит всем кнопкам сразу — какая ждёт, та и
     * считает.
     */
    fun startCountdown(expectMs: Long)

    /** Ответ пришёл или сорвался — отсчёт кончился. */
    fun stopCountdown()

    /** Убрана в ручку или в точку «всё убрано». */
    fun setStacked(value: Boolean)

    /** Складывание Fold идёт: окно снято на время перехода. */
    fun setFolded(value: Boolean)

    /** Экран сложили или повернули: в стопке — вернуться на своё сохранённое место. */
    fun onConfigurationChanged()

    /** Сколько оверлейных окон держит сейчас — перепись для журнала складывания. */
    fun windowCount(): Int

    fun destroy()
}
