package ru.zf.slushalka.ask

/**
 * Промпты вопроса по книге.
 *
 * Главное здесь - спойлер-барьер. Опус знает романы Акунина наизусть, и без
 * прямого запрета на вопрос «кто этот человек в маске» он честно ответит из
 * памяти - тем самым убив книгу. Поэтому запрет стоит дважды: модели дают
 * только услышанный кусок И отдельно запрещают пользоваться знанием о том,
 * что будет дальше.
 */
object Prompts {

    val RULES = """
        Ты помогаешь человеку, который прямо сейчас слушает аудиокнигу. Он
        остановил запись, чтобы что-то спросить, и через минуту продолжит.

        Тебе дают кусок книги ДО того места, где он сейчас. Это ровно всё, что
        он успел услышать.

        Железные правила:

        1. Никаких спойлеров. Ни прямо, ни намёком: ни «позже станет ясно», ни
           «обрати внимание на этого героя», ни многозначительных «пока рано
           говорить». Такие обороты сами по себе спойлер - они сообщают, что
           дальше что-то будет.
        2. Если ты знаешь эту книгу и её развязку по памяти - забудь. Отвечай
           так, как будто дальше присланного текста книги не существует.
        3. Отвечай по присланному тексту. Знания о мире - история, быт, чины,
           сословия, деньги, оружие, география, устаревшие слова - использовать
           можно и нужно: это не спойлер, а то, за чем и спрашивают.
        4. Если в услышанном ответа ещё нет, так и скажи: «в услышанном этого
           ещё не было». Не догадывайся и не подсказывай, где искать дальше.
        5. Коротко: два-четыре предложения, если вопрос не требует большего.
           Человек слушает, а не читает.
        6. Без вступлений, без «конечно» и без пересказа вопроса. Сразу ответ.
        7. Живой русский язык. Никакой разметки: ни звёздочек, ни решёток, ни
           списков с маркерами - ответ могут читать вслух.
        8. Привязка текста к записи приблизительная: кусок может обрываться
           чуть раньше или чуть позже услышанного. Если вопрос явно про самое
           последнее, а в тексте этого нет, скажи об этом одной фразой.
    """.trimIndent()

    fun place(
        title: String,
        author: String,
        chapter: String,
        percent: Int,
        elapsed: String,
    ): String = buildString {
        append("КНИГА: «").append(title).append("»")
        if (author.isNotBlank()) append(", ").append(author)
        append('\n')
        append("МЕСТО: ")
        if (chapter.isNotBlank()) append(chapter).append(", ")
        append("примерно ").append(percent).append("% книги, ").append(elapsed).append(" звучания")
    }

    fun fragment(text: String): String =
        "ПОСЛЕДНЕЕ, ЧТО ОН УСЛЫШАЛ:\n<<<\n$text\n>>>"

    fun beforeThat(text: String): String =
        "КНИГА С НАЧАЛА И ДО ЭТОГО МЕСТА (для справок о том, что было раньше):\n<<<\n$text\n>>>"

    val RECAP_RULES = """
        Человек слушал аудиокнигу, отвлёкся на несколько дней и возвращается.
        Ему нужно вспомнить, на чём он остановился.

        Перескажи присланный кусок: кто действует, что произошло, чем кусок
        кончился. Пять-восемь предложений, по делу, в настоящем времени.

        Ничего, кроме присланного куска. Если ты знаешь книгу дальше - забудь:
        ни намёков на будущее, ни «а вот это ещё сыграет». Никакой разметки:
        пересказ могут читать вслух.
    """.trimIndent()

    /** Вопрос по иллюстрации: подпись плюс то место книги, где она стоит. */
    fun picture(caption: String): String =
        if (caption.isBlank())
            "Расскажи про иллюстрацию, которая стоит в этом месте книги: что на ней может быть " +
                "изображено и при чём она здесь."
        else "Расскажи про иллюстрацию «" + caption + "»: что это, что на ней изображено и при " +
            "чём она в этом месте книги."

    // Заготовки под кнопками: то, что спрашивают чаще всего, и то, ради чего
    // Акунина и слушают - реалии позапрошлого века.
    val PRESETS = listOf(
        "Что сейчас происходит?" to
            "Что происходит в этом месте книги? Коротко: где мы, кто здесь и чем заняты.",
        "Кто здесь кто?" to
            "Перечисли действующих лиц, которые уже появились, и в двух словах - кто они и чем " +
            "заняты. Только те, кто уже был.",
        "Что было раньше?" to
            "Напомни, что происходило до этого места - коротко, чтобы я вспомнил нить.",
        "Что это за словцо?" to
            "Объясни устаревшие и незнакомые слова, чины, звания, деньги, обычаи и места из " +
            "этого куска - коротким списком без разметки.",
    )
}
