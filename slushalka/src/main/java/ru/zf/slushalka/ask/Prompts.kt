    fun guideTask(title: String, author: String, part: Int, parts: Int, chapterFrom: Int, chapterTo: Int): String =
        buildString {
            append("КНИГА: «").append(title).append("»")
            if (author.isNotBlank()) append(", ").append(author)
            append(".\n")
            if (parts > 1) {
                append("Это часть ").append(part + 1).append(" из ").append(parts)
                append(": главы ").append(chapterFrom).append("–").append(chapterTo)
                append(". Остальные части обрабатываются отдельно; описывай только то, что есть в этих главах, ")
                append("нумерацию глав сохраняй как в пометках.\n")
            }
            append("Составь справочник по тексту ниже.\n\n")
        }

    fun chapterMark(index: Int, title: String): String = "\n\n=== ГЛАВА $index: $title ===\n\n"
